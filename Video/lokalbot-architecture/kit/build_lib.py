#!/usr/bin/env python3
"""Shared by the three films' build.py: writes index.html and puts the voice's timings in the scenes.

A film's build.py holds one table: its scenes in order, the voice lines each scene carries with the
pause before each line, and the effects on what the picture shows. build() places the lines one
after another, so a scene is as long as its lines need, then writes

  index.html                    the scene hosts, the voice and the effects (generated: never edit)
  compositions/<scene>.html     two generated blocks inside each hand-written scene file:
      /* kit:begin */ ... /* kit:end */      in <style>: kit/kit.css, the look the films share
      /* cues:begin */ ... /* cues:end */    in <script>: CUES and the helpers below
  cues.txt                      the same timings, to read while building a scene

In a scene's script, after the cues block:

  LEN                   seconds this scene's host lasts
  SLOT                  when the next scene takes over (LEN minus the overlap)
  L("a03")              when line a03 starts, in this scene's time
  E("a03")              when its last word ends
  W("a03", "spoke")     when the word "spoke" starts (third argument: which occurrence, from 1)

so a part appears on the word that names it, and a retake of the voice moves the picture with it.

A scene is a dict:
  id         the composition (compositions/<id>.html)
  lines      [(line id, seed, pause before it in seconds)]   placed one after another
  lead       seconds before the first pause (default 0.4)
  tail       seconds after the last word (default 0.5)
  length     a fixed slot instead, for a scene with no lines
  overlap    seconds the host stays up after its slot, under the next scene (default 0)
  span       "film": the host covers the whole film and gets every line's cues, in film time
  kit        True: compositions/<id>.html is copied from kit/<id>.html on every build
  variables  dict for the host's data-variable-values
  effects    [(name, file, when, volume)]         when: seconds in scene time, or a function of cues
  loops      [(name, when, seconds, volume)]      typing.mp3, its silent first 0.45 s skipped
"""
import json
import math
import re
import shutil
import struct
import subprocess
from pathlib import Path

KIT = Path(__file__).resolve().parent
FPS = 30

# HyperFrames' bundled effects: where each file's peak sits, and how long the file is.
PEAK = {"pop": 0.119, "click-soft": 0.072, "whoosh-short": 0.162, "whoosh": 0.162, "key-press": 0.077,
        "impact-bass-1": 0.073}
LENGTH = {"pop": 0.72, "click-soft": 0.37, "whoosh-short": 0.57, "whoosh": 0.57, "key-press": 0.4,
          "impact-bass-1": 2.12}
SPEECH_LEVEL = -21.0  # dB RMS every take is brought to
PEAK_CEILING = -1.4   # dBFS no take passes after its gain

HEAD = """<!doctype html>
<!-- Generated by build.py. Edit the scene table and the sound there, the pictures in compositions/. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        margin: 0;
        width: 1920px;
        height: 1080px;
        overflow: hidden;
        background: GROUND;
      }
    </style>
  </head>
  <body>
"""

CUE_BLOCK = re.compile(r"/\* cues:begin \*/.*?/\* cues:end \*/", re.S)
KIT_BLOCK = re.compile(r"/\* kit:begin \*/.*?/\* kit:end \*/", re.S)


class Cues:
    """A scene's timings, for the effects table: the same L, E and W the scene's script gets."""

    def __init__(self, length, lines):
        self.LEN = length
        self.lines = lines

    def L(self, line):
        return self.lines[line]["start"]

    def E(self, line):
        return self.lines[line]["end"]

    def W(self, line, word, nth=1):
        hits = [at for said, at in self.lines[line]["words"] if said == word.lower()]
        if len(hits) < nth:
            raise SystemExit(f"no cue {line}/{word}")
        return hits[nth - 1]


def frames(seconds):
    """Up to the next whole frame, so scenes meet on a frame."""
    return math.ceil(round(seconds * FPS, 4)) / FPS


def measure(path):
    """(seconds to the last sound, gain to the shared speech level) for one take."""
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", str(path), "-ac", "1", "-ar", "8000", "-f", "s16le", "-"],
                         check=True, capture_output=True).stdout
    data = struct.unpack(f"<{len(raw) // 2}h", raw)
    peak = max(abs(s) for s in data) or 1
    floor = peak * 0.03
    first = next(i for i, s in enumerate(data) if abs(s) > floor)
    last = max(i for i, s in enumerate(data) if abs(s) > floor)
    rms = math.sqrt(sum(s * s for s in data[first:last + 1]) / max(1, last - first + 1))
    gain_db = min(SPEECH_LEVEL - 20 * math.log10(rms / 32768), PEAK_CEILING - 20 * math.log10(peak / 32768), 0.0)
    return last / 8000, round(10 ** (gain_db / 20), 2)


def spoken_words(row):
    """[(word, seconds into the take)], lower-cased, punctuation at either end dropped."""
    alignment = row["alignment"]
    out, current, begun = [], "", None
    for char, start in zip(alignment["characters"], alignment["character_start_times_seconds"]):
        if char.isspace():
            if current:
                out.append((current, begun))
            current, begun = "", None
        else:
            if begun is None:
                begun = start
            current += char
    if current:
        out.append((current, begun))
    clean = [(re.sub(r"^\W+|\W+$", "", word.lower()), at) for word, at in out]
    return [(word, at) for word, at in clean if word]


def place(film, scenes):
    """Give every scene its start, slot and cues. Returns the film's length."""
    rows = {(row["id"], row["seed"]): row for row in json.loads((film / "voice/generation.json").read_text())["rows"]}
    at = 0.0
    for scene in scenes:
        if scene.get("span") == "film":
            continue
        scene["start"] = round(at, 4)
        clock = scene.get("lead", 0.4)
        scene["cues"] = {}
        for line, seed, pause in scene.get("lines", []):
            file = f"assets/voice/{line}-s{seed}.mp3"
            last, gain = measure(film / file)
            clock += pause
            scene["cues"][line] = {
                "start": round(clock, 3), "end": round(clock + last, 3), "file": file, "gain": gain,
                "clip": round(min(last + 0.2, rows[(line, seed)]["duration"]), 2),
                "words": [[word, round(clock + said, 3)] for word, said in spoken_words(rows[(line, seed)])],
            }
            clock += last
        slot = frames(scene["length"] if "length" in scene else clock + scene.get("tail", 0.5))
        scene["slot"] = slot
        scene["duration"] = round(slot + scene.get("overlap", 0), 4)
        at += slot
    total = round(at, 4)
    for scene in scenes:
        if scene.get("span") == "film":
            scene["start"], scene["slot"], scene["duration"] = 0.0, total, total
            scene["cues"] = {}
            for other in scenes:
                if other.get("span") == "film":
                    continue
                for line, cue in other["cues"].items():
                    shift = other["start"]
                    scene["cues"][line] = {**cue, "start": round(cue["start"] + shift, 3), "end": round(cue["end"] + shift, 3),
                                           "words": [[word, round(said + shift, 3)] for word, said in cue["words"]]}
    return total


def cue_script(scene):
    data = {"length": scene["duration"], "slot": scene["slot"],
            "lines": {line: {"start": cue["start"], "end": cue["end"], "words": cue["words"]}
                      for line, cue in scene["cues"].items()}}
    return ("/* cues:begin */\n"
            "    // Written by build.py from the voice's timings: never edit between these two marks.\n"
            f"    const CUES = {json.dumps(data)};\n"
            "    const LEN = CUES.length;\n"
            "    const SLOT = CUES.slot;\n"
            "    const L = (id) => CUES.lines[id].start;\n"
            "    const E = (id) => CUES.lines[id].end;\n"
            "    const W = (id, word, nth = 1) => {\n"
            "      const hits = CUES.lines[id].words.filter((said) => said[0] === word.toLowerCase());\n"
            "      if (hits.length < nth) throw new Error(`no cue ${id}/${word}`);\n"
            "      return hits[nth - 1][1];\n"
            "    };\n"
            "    gsap.config({ force3D: false }); // 2D transforms, so type stays sharp under a camera move\n"
            "    /* cues:end */")


def inject(film, scene):
    path = film / f"compositions/{scene['id']}.html"
    if scene.get("kit"):
        shutil.copyfile(KIT / f"{scene['id']}.html", path)
    text = path.read_text()
    if not CUE_BLOCK.search(text):
        raise SystemExit(f"{path.name}: no /* cues:begin */ /* cues:end */ block in its script")
    text = CUE_BLOCK.sub(lambda _: cue_script(scene), text, count=1)
    if KIT_BLOCK.search(text):
        kit = "/* kit:begin */\n" + (KIT / "kit.css").read_text().rstrip() + "\n    /* kit:end */"
        text = KIT_BLOCK.sub(lambda _: kit, text, count=1)
    path.write_text(text)


def build(film, ground, scenes):
    film = Path(film)
    total = place(film, scenes)
    out = [HEAD.replace("GROUND", ground)]
    out.append(f'    <div id="root" data-composition-id="main" data-start="0" data-duration="{total:g}" '
               'data-width="1920" data-height="1080">\n')
    for index, scene in enumerate(scenes):
        inject(film, scene)
        variables = ""
        if scene.get("variables"):
            variables = f"\n        data-variable-values='{json.dumps(scene['variables'])}'"
        out.append(f'      <div id="{scene["id"]}" data-composition-id="{scene["id"]}" '
                   f'data-composition-src="compositions/{scene["id"]}.html"\n'
                   f'        data-start="{scene["start"]:g}" data-duration="{scene["duration"]:g}" '
                   f'data-track-index="{index + 1}" data-track-kind="graphics"{variables}\n'
                   f'        data-width="1920" data-height="1080" style="z-index: {scene.get("z", index + 10)}"></div>\n')
    out.append("\n      <!-- The voice: ElevenLabs takes, each brought to the same speech level. -->\n")
    spoken = 0
    for scene in scenes:
        if scene.get("span") == "film":
            continue
        for line, cue in scene["cues"].items():
            spoken += 1
            out.append(f'      <audio id="voice-{line}" class="clip" data-start="{round(scene["start"] + cue["start"], 3):g}" '
                       f'data-duration="{cue["clip"]:g}" data-track-index="{40 + spoken % 2}" data-volume="{cue["gain"]:g}" '
                       f'src="{cue["file"]}"></audio>\n')
    out.append("\n      <!-- Effects on what the picture shows, under the voice (HyperFrames' bundled library). -->\n")
    track = 0
    for scene in scenes:
        cues = Cues(scene["duration"], scene["cues"])
        for name, file, when, volume in scene.get("effects", []):
            local = when(cues) if callable(when) else when
            start = round(scene["start"] + local + 1 / FPS - PEAK[file], 3)
            track += 1
            out.append(f'      <audio id="sfx-{name}" class="clip" data-start="{max(start, 0):g}" data-duration="{LENGTH[file]:g}" '
                       f'data-track-index="{42 + track % 2}" data-volume="{volume:g}" src="assets/sfx/{file}.mp3"></audio>\n')
        for name, when, seconds, volume in scene.get("loops", []):
            local = when(cues) if callable(when) else when
            out.append(f'      <audio id="sfx-{name}" class="clip" data-start="{round(scene["start"] + local, 3):g}" '
                       f'data-duration="{seconds:g}" data-track-index="44" data-volume="{volume:g}" data-media-start="0.45" '
                       'data-fade-out="0.08" src="assets/sfx/typing.mp3"></audio>\n')
    out.append(f"""    </div>
    <script>
      // Every scene runs its own timeline; the root only spans the film.
      const tl = gsap.timeline({{ paused: true }});
      tl.set({{}}, {{}}, {total:g});
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
""")
    (film / "index.html").write_text("".join(out))
    report = [f"{total:g} s"]
    for scene in scenes:
        report.append(f"\n{scene['id']}: starts {scene['start']:g}, slot {scene['slot']:g}, host {scene['duration']:g}")
        for line, cue in scene["cues"].items():
            words = "  ".join(f"{word}@{said:g}" for word, said in cue["words"])
            report.append(f"  {line}  {cue['start']:6.2f} to {cue['end']:6.2f}  (film {scene['start'] + cue['start']:6.2f})  gain {cue['gain']:g}")
            report.append(f"      {words}")
    (film / "cues.txt").write_text("\n".join(report) + "\n")
    print("\n".join(line for line in report if not line.startswith("      ")))
    return total
