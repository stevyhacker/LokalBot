#!/usr/bin/env python3
"""Write index.html: where each scene starts, and every sound against the picture it belongs to.

    python3 build.py

The scenes are hand-written (compositions/*.html) and run on their own clocks. This file
holds the order, how long each scene has the screen, and the voice and effects in each
scene's own time, so moving a scene moves its sound with it. index.html is generated: edit
here, not there.
"""
import json
import struct
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent

# (scene, seconds it has the screen before the next one takes over, seconds its host outlives that).
# The notes stay behind the search panel until the swipe, so their host spans both.
SCENES = [
    ("call", 6.2, 0),
    ("notes", 5.8, 5.15 + 0.55),
    ("search", 5.15, 0.55),
    ("autocomplete", 5.55, 0.55),
    ("dictation", 7.2, 0.45),
    ("agent", 5.2, 0.55),
    ("timeline", 5.3, 0.5),
    ("endcard", 8.0, 0),
]
# Where the voice's lines start, in their scene's time (voice/narration.json; takes in VOICE).
VOICE = {
    "call": [("01-call", 11, 0.35)],
    "notes": [("02-notes", 11, 0.25)],
    "search": [("03-search", 11, 0.2)],
    "autocomplete": [("04-type", 29, 0.2)],
    # "request" is the line dictated in the scene: the same take the app heard, placed where
    # the take's recording started (the key goes down at 0.62 s; the file leads with 0.55 s).
    "dictation": [("05-say", 11, 0.1), ("request", 11, 1.17)],
    "agent": [("06-agent", 11, 0.55)],
    "timeline": [("07-day", 29, 0.4)],
    "endcard": [("08-end", 11, 0.62)],
}
# Effects, in their scene's time: (name, file, when its picture happens, volume).
# Each file is started early by where its peak sits, so the peak lands a frame after the picture.
PEAK = {"pop": 0.119, "click-soft": 0.072, "whoosh-short": 0.162, "whoosh": 0.162, "key-press": 0.077,
        "impact-bass-1": 0.073}
LENGTH = {"pop": 0.72, "click-soft": 0.37, "whoosh-short": 0.57, "whoosh": 0.57, "key-press": 0.4,
          "impact-bass-1": 2.12}
EFFECTS = {
    "call": [("mark", "pop", 3.65, 0.25)],
    "notes": [("click", "click-soft", 3.295, 0.5)],
    "search": [("panel", "whoosh-short", 0.07, 0.3)]
              + [(f"down-{i}", "key-press", at, 0.3) for i, at in enumerate([2.08, 2.56, 3.05, 3.53], 1)]
              + [("swipe", "whoosh", 5.40, 0.3)],
    "autocomplete": [(f"tab-{i}", "key-press", at, 0.35)
                     for i, at in enumerate([2.508, 2.82, 3.14, 3.45, 3.77, 4.08, 4.40], 1)]
                    + [("page", "whoosh-short", 5.8, 0.22)],
    "dictation": [("flood", "whoosh-short", 7.4, 0.3)],
    "agent": [("return", "key-press", 2.05, 0.35)],
    "timeline": [("swipe-day", "whoosh", 0.25, 0.3), ("click-day", "click-soft", 1.23, 0.5)],
    "endcard": [("lockup", "impact-bass-1", 0.68, 0.3)],
}
# Typing loops: (name, start, seconds). typing.mp3 is silent for its first 0.45 s, which is skipped.
TYPING = {
    "search": [("type-search", 0.476, 0.78)],
    "autocomplete": [("type-doc", 0.47, 0.95)],
    "agent": [("type-agent", 0.75, 1.05)],
}
# Per-line gain that brings every take to the same speech level (-21 dB RMS), measured by
# voice/levels in generation.json's takes; none peaks above -1.4 dBFS after it.
VOICE_GAIN = {"01-call": 0.99, "02-notes": 1.02, "03-search": 0.83, "04-type": 0.87, "05-say": 0.62,
              "06-agent": 0.78, "07-day": 0.81, "08-end": 0.95, "request": 0.83}

HEAD = """<!doctype html>
<!-- Generated by build.py. Edit the scene order, lengths and sound there. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        margin: 0;
        width: 1920px;
        height: 1080px;
        overflow: hidden;
        background: #0e151d;
      }
    </style>
  </head>
  <body>
"""


def speech_end(path):
    """Seconds to the last sound in a take: ElevenLabs files end in up to a second of silence."""
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", str(path), "-ac", "1", "-ar", "8000", "-f", "s16le", "-"],
                         check=True, capture_output=True).stdout
    samples = struct.unpack(f"<{len(raw) // 2}h", raw)
    floor = max(abs(s) for s in samples) * 0.03
    last = max(i for i, s in enumerate(samples) if abs(s) > floor)
    return last / 8000


def main():
    starts, at = {}, 0.0
    for scene, slot, _ in SCENES:
        starts[scene] = round(at, 3)
        at += slot
    total = round(at, 3)
    out = [HEAD]
    out.append(f'    <div id="root" data-composition-id="main" data-start="0" data-duration="{total:g}" '
               'data-width="1920" data-height="1080">\n')
    backdrop = {"floodAt": starts["agent"], "exitAt": starts["endcard"], "length": total}
    out.append('      <div id="backdrop" data-composition-id="backdrop" data-composition-src="compositions/backdrop.html"\n'
               f'        data-start="0" data-duration="{total:g}" data-track-index="1" data-track-kind="graphics"\n'
               f"        data-variable-values='{json.dumps(backdrop)}'\n"
               '        data-width="1920" data-height="1080" style="z-index: 1"></div>\n\n')
    for index, (scene, slot, tail) in enumerate(SCENES):
        out.append(f'      <div id="{scene}" data-composition-id="{scene}" data-composition-src="compositions/{scene}.html"\n'
                   f'        data-start="{starts[scene]:g}" data-duration="{round(slot + tail, 3):g}" '
                   f'data-track-index="{index + 2}" data-track-kind="graphics"\n'
                   f'        data-width="1920" data-height="1080" style="z-index: {index + 10}"></div>\n')
    out.append("\n      <!-- The voice: ElevenLabs takes, levelled per line. -->\n")
    spoken = 0
    for scene, _, _ in SCENES:
        for line, seed, local in VOICE.get(scene, []):
            file = f"assets/voice/{line}-s{seed}.mp3"
            length = round(speech_end(HERE / file) + 0.2, 2)
            spoken += 1
            out.append(f'      <audio id="voice-{line}" class="clip" data-start="{round(starts[scene] + local, 3):g}" '
                       f'data-duration="{length:g}" data-track-index="{19 + spoken % 2}" data-volume="{VOICE_GAIN[line]:g}" '
                       f'src="{file}"></audio>\n')
    out.append("\n      <!-- Effects on the actions the picture shows, kept under the voice (bundled HyperFrames library). -->\n")
    track = 0
    for scene, _, _ in SCENES:
        for name, file, local, volume in EFFECTS.get(scene, []):
            start = round(starts[scene] + local + 1 / 30 - PEAK[file], 3)
            track += 1
            out.append(f'      <audio id="sfx-{name}" class="clip" data-start="{start:g}" data-duration="{LENGTH[file]:g}" '
                       f'data-track-index="{21 + track % 2}" data-volume="{volume:g}" src="assets/sfx/{file}.mp3"></audio>\n')
        for name, local, seconds in TYPING.get(scene, []):
            out.append(f'      <audio id="sfx-{name}" class="clip" data-start="{round(starts[scene] + local, 3):g}" '
                       f'data-duration="{seconds:g}" data-track-index="23" data-volume="0.35" data-media-start="0.45" '
                       'data-fade-out="0.08" src="assets/sfx/typing.mp3"></audio>\n')
    out.append(f"""    </div>
    <script>
      // Every scene runs its own timeline; the root only spans the film.
      const tl = gsap.timeline({{ paused: true }});
      tl.set({{}}, {{}}, {total:g});
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
""")
    (HERE / "index.html").write_text("".join(out))
    print(f"{total:g} s")
    for scene, _, _ in SCENES:
        print(f"  {starts[scene]:6.2f}  {scene}")


if __name__ == "__main__":
    main()
