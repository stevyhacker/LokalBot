#!/usr/bin/env python3
"""Keep code comments from coming back, and count down the ones left.

Code in this repository carries no comments. Non-obvious decisions live in
Docs/decisions/, hacks are GitHub issues, and everything else is deleted. The
baseline (Scripts/ci/comment-baseline.json) lists the files that still have
comments and how many comment lines each may keep.

    python3 Scripts/ci/comment-ratchet.py --check          # CI: no file may move off its baseline
    python3 Scripts/ci/comment-ratchet.py --update         # lock in deletions (never raises a count)
    python3 Scripts/ci/comment-ratchet.py --list [PATH...] # every comment block, as JSON lines
    python3 Scripts/ci/comment-ratchet.py --stats [PATH...]
    python3 Scripts/ci/comment-ratchet.py --delete FILE    # delete the blocks FILE lists ({"path", "line"} JSON lines)

Lines a tool reads are not comments and are never counted or deleted: lint and
formatter suppressions, shebangs, `swift-tools-version`, PEP 723 script
metadata, source map URLs, license and copyright notices, and the doc comments
clap turns into `--help` text.
"""

from __future__ import annotations

import argparse
import io
import json
import re
import subprocess
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "Scripts" / "ci" / "comment-baseline.json"

LANGUAGES = {
    ".swift": "swift",
    ".rs": "rust",
    ".kt": "kotlin",
    ".kts": "kotlin",
    ".py": "python",
    ".sh": "shell",
    ".bash": "shell",
    ".js": "js",
    ".mjs": "js",
    ".cjs": "js",
    ".ts": "js",
    ".tsx": "js",
}

EXCLUDED_PREFIXES = ("Benchmarks/", "Video/", "Vendor/", "LICENSES/", "Docs/", "Local/", "dist/")
EXCLUDED_FILES = {"LinuxWindows/crates/lokalbot-i18n/src/catalogs.rs"}
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by")

DIRECTIVES = {
    "swift": r"swiftlint:|swiftformat:|swift-format-ignore|periphery:|sourcery:|swift-tools-version",
    "rust": r"rustfmt::|clippy::|cbindgen:",
    "kotlin": r"ktlint|noinspection|@formatter:|language=",
    "python": r"noqa|type:\s*ignore|pragma:|pylint:|pyright:|mypy:|fmt:\s*(on|off|skip)|isort:|-\*-|ruff:",
    "shell": r"shellcheck|-\*-",
    "js": r"@ts-|eslint|prettier-ignore|global\s|/\s*<reference|@vite-ignore|webpackChunkName|istanbul|c8 ignore"
          r"|[#@]__PURE__|@license|@preserve|[#@]\s*source(Mapping)?URL=|@jsx",
}
NOTICE = re.compile(r"Contains code ported from|copyright|SPDX-License-Identifier|Licensed under|under the (GNU|MIT|Apache)", re.I)
CLAP_DERIVE = re.compile(r"#\[derive\([^)]*\b(Parser|Subcommand|Args|ValueEnum)\b")


@dataclass
class Comment:
    path: str
    start: int
    end: int
    line: int
    end_line: int
    marker: str
    text: str
    full_line: bool
    directive: bool = False


@dataclass
class Block:
    """Consecutive full-line comments with one marker, or one trailing/inline comment."""

    path: str
    parts: list[Comment]

    @property
    def line(self) -> int:
        return self.parts[0].line

    @property
    def end_line(self) -> int:
        return self.parts[-1].end_line

    @property
    def full_line(self) -> bool:
        return self.parts[0].full_line

    @property
    def directive(self) -> bool:
        return any(p.directive for p in self.parts)

    @property
    def text(self) -> str:
        return "\n".join(p.text for p in self.parts)

    @property
    def counted_lines(self) -> int:
        return self.end_line - self.line + 1 if self.full_line else 1


class Lexer:
    """Finds comments in C-family languages and shell, stepping over string literals."""

    def __init__(self, src: str, lang: str):
        self.s, self.n, self.lang = src, len(src), lang
        self.i = 0
        self.found: list[tuple[int, int, str]] = []
        self.prev = ""

    def at(self, t: str) -> bool:
        return self.s.startswith(t, self.i)

    def line_comment(self, marker: str) -> None:
        start = self.i
        end = self.s.find("\n", self.i)
        self.i = self.n if end == -1 else end
        self.found.append((start, self.i, marker))

    def block_comment(self, nested: bool) -> None:
        start = self.i
        marker = "/**" if self.at("/**") and not self.at("/**/") else "/*"
        depth = 0
        while self.i < self.n:
            if self.at("/*") and (nested or depth == 0):
                depth += 1
                self.i += 2
            elif self.at("*/"):
                depth -= 1
                self.i += 2
                if depth == 0:
                    break
            else:
                self.i += 1
        self.found.append((start, self.i, marker))

    def string(self, closer: str, escapes: bool, interp: str | None = None, multiline: bool = True) -> None:
        while self.i < self.n:
            if interp and self.at(interp):
                self.i += len(interp)
                self.nested_code(")" if interp.endswith("(") else "}")
                continue
            if escapes and self.s[self.i] == "\\":
                self.i += 2
                continue
            if self.at(closer):
                self.i += len(closer)
                return
            if not multiline and self.s[self.i] == "\n":
                return
            self.i += 1

    def nested_code(self, close: str) -> None:
        opener = "(" if close == ")" else "{"
        depth = 1
        while self.i < self.n:
            if self.token():
                continue
            c = self.s[self.i]
            if c == opener:
                depth += 1
            elif c == close:
                depth -= 1
                if depth == 0:
                    self.i += 1
                    return
            self.i += 1

    def word_boundary(self) -> bool:
        return self.i == 0 or not (self.s[self.i - 1].isalnum() or self.s[self.i - 1] == "_")

    def char_literal(self) -> None:
        s, i = self.s, self.i
        if i + 1 < self.n and s[i + 1] == "\\":
            j = s.find("'", i + 2, i + 14)
            if j != -1:
                self.i = j + 1
                return
        if i + 2 < self.n and s[i + 2] == "'" and s[i + 1] != "\n":
            self.i += 3
            return
        self.i += 1

    def token(self) -> bool:
        """Consume a comment or a string literal at the cursor; True if one was consumed."""
        if self.lang == "shell":
            return self.shell_token()
        s, i, lang = self.s, self.i, self.lang
        if self.at("//"):
            marker = "//!" if self.at("//!") else "///" if self.at("///") and not self.at("////") else "//"
            self.line_comment(marker)
            return True
        if self.at("/*"):
            self.block_comment(nested=lang in ("swift", "rust"))
            return True
        if lang == "swift":
            m = re.match(r'(#+)("""|")', s[i:i + 40])
            if m:
                self.i += len(m.group(0))
                self.string(m.group(2) + m.group(1), escapes=False, interp="\\" + m.group(1) + "(")
                return True
            if self.at('"""'):
                self.i += 3
                self.string('"""', escapes=True, interp="\\(")
                return True
            if s[i] == '"':
                self.i += 1
                self.string('"', escapes=True, interp="\\(", multiline=False)
                return True
            if self.at("#/"):
                self.i += 2
                self.string("/#", escapes=True)
                return True
        elif lang == "rust":
            m = re.match(r'(?:b|c)?r(#*)"', s[i:i + 40])
            if m and self.word_boundary():
                self.i += len(m.group(0))
                self.string('"' + m.group(1), escapes=False)
                return True
            if s[i] == '"' or (s[i] in "bc" and s[i + 1:i + 2] == '"' and self.word_boundary()):
                self.i += 1 if s[i] == '"' else 2
                self.string('"', escapes=True)
                return True
            if s[i] == "'" or (s[i] == "b" and s[i + 1:i + 2] == "'" and self.word_boundary()):
                if s[i] == "b":
                    self.i += 1
                self.char_literal()
                return True
        elif lang == "kotlin":
            if self.at('"""'):
                self.i += 3
                self.string('"""', escapes=False, interp="${")
                return True
            if s[i] == '"':
                self.i += 1
                self.string('"', escapes=True, interp="${", multiline=False)
                return True
            if s[i] == "'":
                self.char_literal()
                return True
        elif lang == "js":
            if s[i] in "'\"":
                self.i += 1
                self.string(s[i], escapes=True, multiline=False)
                return True
            if s[i] == "`":
                self.i += 1
                self.string("`", escapes=True, interp="${")
                return True
            if s[i] == "/" and (self.prev == "" or self.prev in "(,=:[!&|?{};+-*%<>~^"):
                self.i += 1
                in_class = False
                while self.i < self.n and self.s[self.i] != "\n":
                    c = self.s[self.i]
                    if c == "\\":
                        self.i += 2
                        continue
                    if c == "[":
                        in_class = True
                    elif c == "]":
                        in_class = False
                    elif c == "/" and not in_class:
                        self.i += 1
                        break
                    self.i += 1
                return True
        return False

    def shell_token(self) -> bool:
        s, i = self.s, self.i
        c = s[i]
        if c == "#":
            prev = s[i - 1] if i > 0 else "\n"
            if prev.isspace() or prev in ";|&(":
                self.line_comment("#")
                return True
            self.i += 1
            return True
        if c == "\\":
            self.i += 2
            return True
        if c == "'":
            end = s.find("'", i + 1)
            self.i = self.n if end == -1 else end + 1
            return True
        if c == '"':
            self.i += 1
            while self.i < self.n and self.s[self.i] != '"':
                if self.s[self.i] == "\\":
                    self.i += 2
                elif self.at("$("):
                    self.i += 2
                    self.nested_code(")")
                else:
                    self.i += 1
            self.i += 1
            return True
        m = re.match(r"<<(-?)\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\2", s[i:i + 80])
        if m and not self.at("<<<"):
            delim, strip = m.group(3), m.group(1) == "-"
            self.i += len(m.group(0))
            while self.i < self.n and self.s[self.i] != "\n":
                if not self.token():
                    self.i += 1
            self.i += 1
            while self.i < self.n:
                end = self.s.find("\n", self.i)
                end = self.n if end == -1 else end
                body = self.s[self.i:end]
                self.i = end + 1
                if (body.lstrip("\t") if strip else body) == delim:
                    break
            return True
        return False

    def run(self) -> list[tuple[int, int, str]]:
        while self.i < self.n:
            c = self.s[self.i]
            if c in " \t\r\n":
                self.i += 1
                continue
            if self.token():
                self.prev = ")"
                continue
            self.prev = c
            self.i += 1
        return self.found


def python_comments(src: str) -> list[tuple[int, int, str]] | None:
    starts = [0]
    for line in src.splitlines(keepends=True):
        starts.append(starts[-1] + len(line))
    try:
        found = []
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            if tok.type == tokenize.COMMENT:
                (r1, c1), (r2, c2) = tok.start, tok.end
                found.append((starts[r1 - 1] + c1, starts[r2 - 1] + c2, "#"))
        return found
    except (tokenize.TokenError, SyntaxError, IndentationError):
        return None


def body_of(text: str) -> str:
    for marker in ("///", "//!", "//", "/**", "/*", "#"):
        if text.startswith(marker):
            text = text[len(marker):]
            break
    return text.removesuffix("*/")


def clap_ranges(src: str) -> list[tuple[int, int]]:
    """Offsets of clap-derived items, whose doc comments are `--help` text."""
    ranges = []
    for m in CLAP_DERIVE.finditer(src):
        brace = src.find("{", m.end())
        semi = src.find(";", m.end())
        if brace == -1 or (semi != -1 and semi < brace):
            continue
        depth, j = 0, brace
        while j < len(src):
            if src[j] == "{":
                depth += 1
            elif src[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        doc_start = src.rfind("\n\n", 0, m.start())
        ranges.append((0 if doc_start == -1 else doc_start, j))
    return ranges


def comments_in(src: str, lang: str, rel: str) -> list[Comment]:
    raw = python_comments(src) if lang == "python" else None
    if raw is None:
        raw = Lexer(src, lang).run()
    directive = re.compile(r"^\s*(" + DIRECTIVES[lang] + ")", re.I)
    clap = clap_ranges(src) if lang == "rust" else []
    out: list[Comment] = []
    in_pep723 = False
    for start, end, marker in raw:
        text = src[start:end]
        line = src.count("\n", 0, start) + 1
        end_line = line + text.count("\n")
        ls = src.rfind("\n", 0, start) + 1
        le = src.find("\n", end)
        le = len(src) if le == -1 else le
        full = not src[ls:start].strip() and not src[end:le].strip()
        c = Comment(rel, start, end, line, end_line, marker, text, full)
        if lang == "python" and re.match(r"#\s*///\s*script\s*$", text):
            in_pep723 = True
        if in_pep723:
            c.directive = True
            in_pep723 = not re.match(r"#\s*///\s*$", text)
        elif marker == "#" and text.startswith("#!") and line == 1:
            c.directive = True
        elif directive.match(body_of(text)):
            c.directive = True
        elif marker == "///" and any(a <= start <= b for a, b in clap):
            c.directive = True
        out.append(c)
    return out


def blocks_in(src: str, lang: str, rel: str) -> list[Block]:
    blocks: list[Block] = []
    for c in comments_in(src, lang, rel):
        prev = blocks[-1] if blocks else None
        if (
            prev
            and c.full_line
            and prev.full_line
            and c.marker == prev.parts[-1].marker
            and c.line == prev.end_line + 1
            and c.directive == prev.parts[-1].directive
        ):
            prev.parts.append(c)
        else:
            blocks.append(Block(rel, [c]))
    for b in blocks:
        if NOTICE.search(b.text):
            for p in b.parts:
                p.directive = True
    return blocks


def in_scope(rel: str) -> bool:
    return (
        Path(rel).suffix in LANGUAGES
        and not rel.startswith(EXCLUDED_PREFIXES)
        and rel not in EXCLUDED_FILES
        and "/node_modules/" not in rel
        and not rel.endswith((".generated.swift", ".min.js", ".d.ts"))
    )


def tracked_files(paths: list[str]) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z", "--", *paths], cwd=ROOT, check=True, capture_output=True).stdout
    return [rel for rel in out.decode().split("\0") if rel and in_scope(rel)]


def read(rel: str) -> str | None:
    try:
        src = (ROOT / rel).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    return None if any(m in src[:600] for m in GENERATED_MARKERS) else src


def scan(paths: list[str]) -> dict[str, list[Block]]:
    found = {}
    for rel in tracked_files(paths):
        src = read(rel)
        if src is not None:
            found[rel] = blocks_in(src, LANGUAGES[Path(rel).suffix], rel)
    return found


def counts(found: dict[str, list[Block]]) -> dict[str, int]:
    per_file = {rel: sum(b.counted_lines for b in blocks if not b.directive) for rel, blocks in found.items()}
    return {rel: n for rel, n in sorted(per_file.items()) if n}


def delete_blocks(src: str, blocks: list[Block]) -> str:
    """Remove the given blocks. Whole comment lines go; trailing comments are cut back to the code."""
    drop: set[int] = set()
    cuts: list[tuple[int, int]] = []
    for b in blocks:
        for p in b.parts:
            if p.full_line:
                drop.update(range(p.line - 1, p.end_line))
                continue
            a, z = p.start, p.end
            ls = src.rfind("\n", 0, a) + 1
            le = src.find("\n", z)
            le = len(src) if le == -1 else le
            if not src[z:le].strip():
                while a > ls and src[a - 1] in " \t":
                    a -= 1
            elif not src[ls:a].strip():
                while z < le and src[z] in " \t":
                    z += 1
            elif src[z:z + 1] == " " and src[a - 1:a] in (" ", "(", "[", "{", "<"):
                z += 1
            cuts.append((a, z))
    for a, z in sorted(cuts, reverse=True):
        src = src[:a] + src[z:]
    lines = src.splitlines(keepends=True)
    keep = [k not in drop for k in range(len(lines))]

    def blank(k: int) -> bool:
        return 0 <= k < len(lines) and keep[k] and not lines[k].strip()

    for first in sorted(k for k in drop if k - 1 not in drop):
        last = first
        while last + 1 in drop:
            last += 1
        before = next((k for k in range(first - 1, -1, -1) if keep[k]), -1)
        after = next((k for k in range(last + 1, len(lines)) if keep[k]), len(lines))
        if blank(after) and (before < 0 or blank(before) or lines[before].rstrip().endswith(("{", "(", "["))):
            keep[after] = False
        elif blank(before) and (after >= len(lines) or lines[after].lstrip().startswith(("}", ")", "]"))):
            keep[before] = False
    result = "".join(line for k, line in enumerate(lines) if keep[k])
    if not result.startswith("#!"):
        result = result.lstrip("\n")
    return result.rstrip("\n") + "\n" if result.strip() else ""


def check_block_shape(src: str, b: Block) -> str | None:
    for p in b.parts:
        if not src[p.start:p.end].startswith(("//", "/*", "#")):
            return f"{b.path}:{p.line} does not start with a comment marker"
        if p.marker in ("/*", "/**") and not src[p.start:p.end].endswith("*/"):
            return f"{b.path}:{p.line} block comment is not closed"
        if not p.full_line and "\n" in src[p.start:p.end]:
            return f"{b.path}:{p.line} inline comment spans lines"
    return None


def run_delete(listing: Path) -> int:
    wanted: dict[str, set[int]] = {}
    for raw in listing.read_text().splitlines():
        if raw.strip():
            row = json.loads(raw)
            wanted.setdefault(row["path"], set()).add(int(row["line"]))
    problems, removed = [], 0
    for rel, starts in sorted(wanted.items()):
        src = read(rel)
        if src is None or not in_scope(rel):
            problems.append(f"{rel}: not a tracked source file in scope")
            continue
        blocks = [b for b in blocks_in(src, LANGUAGES[Path(rel).suffix], rel) if b.line in starts]
        missing = starts - {b.line for b in blocks}
        problems += [f"{rel}:{line} has no comment block starting there" for line in sorted(missing)]
        blocks = [b for b in blocks if not b.directive]
        bad = [msg for b in blocks if (msg := check_block_shape(src, b))]
        if bad:
            problems += bad
            continue
        (ROOT / rel).write_text(delete_blocks(src, blocks), encoding="utf-8")
        removed += len(blocks)
    for p in problems:
        print(p, file=sys.stderr)
    print(f"Deleted {removed} comment blocks in {len(wanted)} files; {len(problems)} skipped.")
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--update", action="store_true")
    mode.add_argument("--list", action="store_true")
    mode.add_argument("--stats", action="store_true")
    mode.add_argument("--delete", type=Path, metavar="FILE")
    ap.add_argument("--all", action="store_true", help="with --list: include tool directives")
    ap.add_argument("--allow-increase", action="store_true", help="with --update: accept higher counts")
    ap.add_argument("paths", nargs="*")
    args = ap.parse_args()

    if args.delete:
        return run_delete(args.delete)
    if (args.check or args.update) and args.paths:
        ap.error("--check and --update always cover the whole repository")

    found = scan(args.paths)

    if args.list:
        for rel, blocks in found.items():
            for b in blocks:
                if b.directive and not args.all:
                    continue
                row = {"path": rel, "line": b.line, "end": b.end_line, "marker": b.parts[0].marker,
                       "full_line": b.full_line, "text": b.text}
                if args.all:
                    row["directive"] = b.directive
                print(json.dumps(row, ensure_ascii=False))
        return 0

    if args.stats:
        stats: dict[str, dict[str, int]] = {}
        for rel, blocks in found.items():
            s = stats.setdefault(LANGUAGES[Path(rel).suffix], dict.fromkeys(
                ("files", "blocks", "comment_lines", "trailing_comments", "directive_lines"), 0))
            s["files"] += 1
            for b in blocks:
                if b.directive:
                    s["directive_lines"] += b.counted_lines
                    continue
                s["blocks"] += 1
                s["comment_lines" if b.full_line else "trailing_comments"] += b.counted_lines
        total = {k: sum(s[k] for s in stats.values()) for k in next(iter(stats.values()), {})}
        print(json.dumps({**stats, "total": total}, indent=2))
        return 0

    current = counts(found)
    baseline = json.loads(BASELINE.read_text()) if BASELINE.exists() else {}

    if args.update:
        grew = {rel: (baseline.get(rel, 0), n) for rel, n in current.items() if n > baseline.get(rel, 0)}
        if grew and not args.allow_increase:
            for rel, (old, new) in grew.items():
                print(f"{rel}: {old} -> {new} comment lines", file=sys.stderr)
            print("Not raising the baseline: delete the new comments (see .claude/skills/delete-comment/SKILL.md).", file=sys.stderr)
            return 1
        BASELINE.write_text(json.dumps(current, indent=1, sort_keys=True) + "\n")
        print(f"Baseline: {sum(current.values())} comment lines in {len(current)} files.")
        return 0

    failures = compare(current, baseline)
    if failures:
        print("\n".join(failures))
    print(f"Comment lines: {sum(current.values())} (baseline {sum(baseline.values())}).")
    return 1 if failures else 0


def compare(current: dict[str, int], baseline: dict[str, int]) -> list[str]:
    failures = []
    for rel in sorted(set(current) | set(baseline)):
        now, allowed = current.get(rel, 0), baseline.get(rel, 0)
        if now > allowed:
            failures.append(f"::error file={rel}::{rel} has {now} comment lines; the baseline allows {allowed}. "
                            "Code takes no new comments: record a decision in Docs/decisions/, file an issue for a "
                            "hack, or delete it (.claude/skills/delete-comment/SKILL.md).")
        elif now < allowed:
            failures.append(f"::error file={rel}::{rel} is down to {now} comment lines from {allowed}. "
                            "Lock that in with: python3 Scripts/ci/comment-ratchet.py --update")
    return failures


if __name__ == "__main__":
    sys.exit(main())
