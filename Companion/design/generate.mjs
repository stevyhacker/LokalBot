#!/usr/bin/env node
// Generates the companion apps' design tokens from tokens.json.
// Usage: node Companion/design/generate.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const header = 'Generated by Companion/design/generate.mjs from Companion/design/tokens.json. Do not edit.';

// "#RRGGBB" or "#RRGGBBAA" -> { r, g, b, a } bytes
function parse(hex) {
  const h = hex.replace('#', '');
  if (!/^([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(h)) throw new Error(`bad colour ${hex}`);
  const n = (i) => parseInt(h.slice(i, i + 2), 16);
  return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) : 255 };
}
const rgbaHex = (c) => '0x' + [c.r, c.g, c.b, c.a].map((v) => v.toString(16).padStart(2, '0').toUpperCase()).join('');
const argbHex = (c) => '0x' + [c.a, c.r, c.g, c.b].map((v) => v.toString(16).padStart(2, '0').toUpperCase()).join('');

const colorNames = Object.keys(tokens.colors).filter((k) => !k.startsWith('$'));
const num = (v) => (Number.isInteger(v) ? `${v}` : `${v}`);

// ---------- Swift ----------
const swift = [];
swift.push(`// ${header}`);
swift.push('');
swift.push('/// A colour with light and dark values as 0xRRGGBBAA.');
swift.push('public struct LBColorToken: Sendable, Hashable {');
swift.push('    public let light: UInt32');
swift.push('    public let dark: UInt32');
swift.push('    public init(light: UInt32, dark: UInt32) { self.light = light; self.dark = dark }');
swift.push('}');
swift.push('');
swift.push('public enum LBTokens {');
swift.push('    public enum Colors {');
for (const name of colorNames) {
  const t = tokens.colors[name];
  swift.push(`        /// ${t.use}`);
  swift.push(`        public static let ${name} = LBColorToken(light: ${rgbaHex(parse(t.light))}, dark: ${rgbaHex(parse(t.dark))})`);
}
swift.push('    }');
swift.push('');
swift.push('    /// Speaker palette; index 0 is the person themselves.');
swift.push('    public static let speakers: [LBColorToken] = [');
tokens.speakers.light.forEach((l, i) => {
  swift.push(`        LBColorToken(light: ${rgbaHex(parse(l))}, dark: ${rgbaHex(parse(tokens.speakers.dark[i]))}),`);
});
swift.push('    ]');
swift.push('');
swift.push(`    public static let nameColorSaturation: Double = ${tokens.nameColor.saturation}`);
swift.push(`    public static let nameColorBrightness: Double = ${tokens.nameColor.brightness}`);
swift.push('');
swift.push('    public enum Radius {');
for (const [k, v] of Object.entries(tokens.radius)) swift.push(`        public static let ${k}: Double = ${num(v)}`);
swift.push('    }');
swift.push('');
swift.push('    public enum Spacing {');
for (const [k, v] of Object.entries(tokens.spacing)) swift.push(`        public static let ${k}: Double = ${num(v)}`);
swift.push('    }');
swift.push('');
swift.push('    /// Animation durations in seconds.');
swift.push('    public enum Motion {');
for (const [k, v] of Object.entries(tokens.motion)) if (!k.startsWith('$')) swift.push(`        public static let ${k}: Double = ${num(v)}`);
swift.push('    }');
swift.push('}');
swift.push('');

// ---------- Kotlin ----------
const kt = [];
kt.push(`// ${header}`);
kt.push('package me.dotenv.lokalbot.companion.ui.theme');
kt.push('');
kt.push('import androidx.compose.ui.graphics.Color');
kt.push('import androidx.compose.ui.unit.dp');
kt.push('');
kt.push('data class LokalBotPalette(');
kt.push(colorNames.map((n) => `    val ${n}: Color,`).join('\n'));
kt.push('    val speakers: List<Color>,');
kt.push(')');
kt.push('');
kt.push('object LokalBotTokens {');
for (const mode of ['light', 'dark']) {
  kt.push(`    val ${mode === 'light' ? 'Light' : 'Dark'} = LokalBotPalette(`);
  for (const n of colorNames) kt.push(`        ${n} = Color(${argbHex(parse(tokens.colors[n][mode]))}),`);
  kt.push(`        speakers = listOf(${tokens.speakers[mode].map((h) => `Color(${argbHex(parse(h))})`).join(', ')}),`);
  kt.push('    )');
}
kt.push('');
kt.push(`    const val NAME_COLOR_SATURATION = ${tokens.nameColor.saturation}f`);
kt.push(`    const val NAME_COLOR_BRIGHTNESS = ${tokens.nameColor.brightness}f`);
kt.push('');
kt.push('    object Radius {');
for (const [k, v] of Object.entries(tokens.radius)) kt.push(`        val ${k} = ${num(v)}.dp`);
kt.push('    }');
kt.push('');
kt.push('    object Spacing {');
for (const [k, v] of Object.entries(tokens.spacing)) kt.push(`        val ${k} = ${num(v)}.dp`);
kt.push('    }');
kt.push('');
kt.push('    /** Animation durations in milliseconds. */');
kt.push('    object Motion {');
for (const [k, v] of Object.entries(tokens.motion)) if (!k.startsWith('$')) kt.push(`        const val ${k} = ${Math.round(v * 1000)}`);
kt.push('    }');
kt.push('}');
kt.push('');

const outputs = [
  [join(root, 'ios/LokalBotCompanionKit/Sources/LokalBotCompanionKit/Design/LBTokens.generated.swift'), swift.join('\n')],
  [join(root, 'android/app/src/main/java/me/dotenv/lokalbot/companion/ui/theme/LokalBotTokens.kt'), kt.join('\n')],
];
for (const [path, text] of outputs) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote ${path.replace(root + '/', 'Companion/')}`);
}
