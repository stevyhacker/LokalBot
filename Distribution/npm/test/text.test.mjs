import assert from 'node:assert/strict';
import test from 'node:test';

import { actionsInCommand, classifyPrompt, projectName } from '../src/text.mjs';

test('only what a person typed counts as a request', () => {
  assert.deepEqual(classifyPrompt('add a retry to the upload job'), { kind: 'prompt', words: 7 });
  assert.equal(classifyPrompt(''), null);
  assert.equal(classifyPrompt('<system-reminder>Today is Tuesday.</system-reminder>'), null);
  assert.equal(classifyPrompt('Caveat: The messages below were generated by the user while running local commands.'), null);
  assert.equal(classifyPrompt('[Request interrupted by user]'), null);
  assert.equal(classifyPrompt('<local-command-stdout>ok</local-command-stdout>'), null);
  assert.equal(classifyPrompt('<environment_context>\n<cwd>/tmp</cwd>'), null, 'an unclosed harness tag');
});

test('harness context around a request is not counted as its words', () => {
  const raw = '<system-reminder>\nA long reminder that the person never wrote.\n</system-reminder>\nrename the flag';
  assert.deepEqual(classifyPrompt(raw), { kind: 'prompt', words: 3 });
  const pasted = 'what does this mean <pasted_content id="1">one two three four five</pasted_content id="1">';
  assert.deepEqual(classifyPrompt(pasted), { kind: 'prompt', words: 4 });
  const codex = '# Context from my IDE setup:\n## Open tabs:\n- main.rs\n## My request for Codex:\nfix the failing test';
  assert.deepEqual(classifyPrompt(codex), { kind: 'prompt', words: 4 });
});

test('slash commands, terminal commands and scheduled runs are told apart', () => {
  assert.equal(classifyPrompt('<command-name>/clear</command-name><command-args></command-args>'), null);
  assert.equal(classifyPrompt('<command-name>/code-review</command-name><command-args>high</command-args>').kind, 'command');
  assert.deepEqual(classifyPrompt('<bash-input>git status</bash-input>'), { kind: 'terminal', words: 0, command: 'git status' });
  assert.equal(classifyPrompt('<heartbeat><automation_id>nightly</automation_id></heartbeat>').kind, 'scheduled');
  assert.equal(classifyPrompt('<scheduled-task name="weekly report">run it</scheduled-task>').kind, 'scheduled');
});

test('a pasted wall of text does not count as thousands of typed words', () => {
  assert.equal(classifyPrompt('word '.repeat(50000)).words, 2000);
});

test('commits, pull requests, releases, pushes and test runs are read from commands', () => {
  const actions = actionsInCommand('git add -A && git commit -m "Fix the upload retry" && git push origin main');
  assert.deepEqual(actions.commits, ['Fix the upload retry']);
  assert.equal(actions.pushed, true);
  assert.equal(actions.ranTests, false);

  const heredoc = 'git commit -m "$(cat <<\'EOF\'\nAdd the importer\n\nLonger body.\nEOF\n)"';
  assert.deepEqual(actionsInCommand(heredoc).commits, ['Add the importer']);

  const pullRequest = actionsInCommand('gh pr create --title "Add the importer" --body "x" && gh pr merge 412 --squash');
  assert.deepEqual(pullRequest.pullRequestsOpened, ['Add the importer']);
  assert.deepEqual(pullRequest.pullRequestsMerged, ['412']);
  assert.deepEqual(actionsInCommand('gh pr merge --auto').pullRequestsMerged, ['']);
  assert.deepEqual(actionsInCommand('gh release create v1.2.0 --notes x').releases, ['v1.2.0']);

  for (const command of ['cargo test -p core', 'npm test', 'pnpm run test', 'pytest -q', 'go test ./...', 'node --test test/', 'xcodebuild -scheme App test', 'make test']) {
    assert.equal(actionsInCommand(command).ranTests, true, command);
  }
  for (const command of ['git status', 'echo "the latest news"', 'ls tests']) {
    assert.equal(actionsInCommand(command).ranTests, false, command);
  }
});

test('a Codex argv is unwrapped to the script it ran', () => {
  assert.deepEqual(actionsInCommand('["/bin/zsh","-lc","git commit -m \'Tidy the readme\'"]').commits, ['Tidy the readme']);
  assert.deepEqual(actionsInCommand(['/bin/zsh', '-lc', 'git push']).pushed, true);
  assert.deepEqual(actionsInCommand(undefined).commits, []);
});

test('a folder is named for its repository, or not at all', () => {
  assert.equal(projectName('/Users/maya/code/harbor-app'), 'harbor-app');
  assert.equal(projectName('/Users/maya/code/harbor-app/.claude/worktrees/quiet-fox'), 'harbor-app');
  assert.equal(projectName('/Users/maya/.codex/worktrees/1a2b/tide-api'), 'tide-api');
  assert.equal(projectName('C:\\Users\\maya\\code\\kiln'), 'kiln');
  assert.equal(projectName('/Users/maya', 'maya'), null);
  assert.equal(projectName('/Users/maya/Documents/GitHub'), null);
  assert.equal(projectName('/tmp/scratch-2026-10-19-6f7eb7'), null);
  assert.equal(projectName(''), null);
});
