#!/usr/bin/env python3
"""Embed the macOS interface catalogs in the Rust app, without an Apple runtime.

Run after editing Localizable.strings or AppLanguage.swift. --check is used by CI.
Desktop-only copy lives in localizations/<locale>.json and cannot override shared copy.
No translation service is used at build time or while running the app.
"""

import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "LinuxWindows/crates/lokalbot-i18n/src/catalogs.rs"
FIELDS = re.compile(r'\{\w+\}|%(?:\d+\$)?(?:lld|ld|[diufgs@])')
BIDI_CONTROLS = re.compile('[\u061c\u200e\u200f\u202a-\u202e\u2066-\u2069]')
# Zero-width space, soft hyphen and word joiner: invisible, usually left by a
# translation tool, and denied by clippy in the generated Rust.
INVISIBLE = re.compile('[\u200b\u00ad\u2060]')
KEYBOARD_TOKENS = re.compile(r'\b(?:Ctrl|Alt|Shift)(?:\+[A-Za-z]+)+|\b(?:Return|Tab|Esc)\b', re.ASCII)


def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate localization key: {key}")
        result[key] = value
    return result


def read_desktop_catalogs(codes):
    directory = ROOT / "LinuxWindows/localizations"
    actual = {p.stem for p in directory.glob("*.json")}
    if actual != set(codes):
        raise ValueError(f"Desktop languages differ from macOS: {actual ^ set(codes)}")
    catalogs = {code: json.loads((directory / f"{code}.json").read_text(), object_pairs_hook=unique_pairs) for code in codes}
    english = catalogs["en"]
    for code, catalog in catalogs.items():
        if catalog.keys() != english.keys():
            raise ValueError(f"{code}: desktop keys differ from English: {catalog.keys() ^ english.keys()}")
        for key, value in catalog.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{code}: empty translation: {key}")
            if Counter(FIELDS.findall(key)) != Counter(FIELDS.findall(value)):
                raise ValueError(f"{code}: changed placeholders: {key} => {value}")
            if Counter(KEYBOARD_TOKENS.findall(key)) != Counter(KEYBOARD_TOKENS.findall(value)):
                raise ValueError(f"{code}: changed keyboard names: {key} => {value}")
            if key.count('\n') != value.count('\n') or BIDI_CONTROLS.search(value):
                raise ValueError(f"{code}: changed line breaks or embedded direction controls: {key}")
            if INVISIBLE.search(value):
                raise ValueError(f"{code}: invisible character in translation: {key}")
            if code == "en" and value != key:
                raise ValueError(f"English source key differs from value: {key}")
    return catalogs


def read_strings(path):
    result = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("//"):
            continue
        match = re.fullmatch(r'("(?:[^"\\]|\\.)*") = ("(?:[^"\\]|\\.)*");', line)
        if not match:
            raise ValueError(f"{path}: invalid entry: {line}")
        key, value = map(json.loads, match.groups())
        if key in result:
            raise ValueError(f"{path}: duplicate key: {key}")
        result[key] = value
    return result


def rust_string(value):
    # JSON's Unicode escapes differ from Rust's. Keep non-ASCII text literal,
    # except invisible characters, which Rust gets as escapes.
    literal = json.dumps(value, ensure_ascii=False).replace("\\b", "\\u{8}").replace("\\f", "\\u{c}")
    return INVISIBLE.sub(lambda m: f"\\u{{{ord(m.group()):x}}}", literal)


def generate():
    language_source = (ROOT / "LokalBot/Models/AppLanguage.swift").read_text()
    cases = dict(re.findall(r'case (\w+) = "([^"]+)"', language_source))
    names = dict(re.findall(r'case \.(\w+): "([^"]+)"', language_source.split("var englishName")[0]))
    english_names = dict(re.findall(r'case \.(\w+): "([^"]+)"', language_source.split("var englishName")[1]))
    english = read_strings(ROOT / "LokalBot/Resources/en.lproj/Localizable.strings")
    desktop = read_desktop_catalogs(cases.values())
    lines = ["// Generated by scripts/sync-localizations.py. Edit the source catalogs instead.",
             "use super::Language;", "pub const LANGUAGES: &[Language] = &["]
    for case, code in cases.items():
        rtl = "true" if code in ("ar", "ar-EG", "ur") else "false"
        lines.append(f"    Language {{ code: {rust_string(code)}, name: {rust_string(names[case])}, english_name: {rust_string(english_names[case])}, rtl: {rtl} }},")
    lines.extend([
        "];", "",
        "// One sorted table per language, searched by key. A single `match` over",
        "// every string ran rustc out of memory in release builds.",
    ])
    tables = []
    for code in cases.values():
        catalog = read_strings(ROOT / f"LokalBot/Resources/{code}.lproj/Localizable.strings")
        if catalog.keys() != english.keys():
            raise ValueError(f"{code}: keys differ from English")
        for key, value in catalog.items():
            if not value.strip() or Counter(FIELDS.findall(english[key])) != Counter(FIELDS.findall(value)):
                raise ValueError(f"{code}: empty shared translation or changed placeholders: {key}")
            if english[key].count('\n') != value.count('\n') or BIDI_CONTROLS.search(value):
                raise ValueError(f"{code}: shared line breaks or direction controls differ: {key}")
        if catalog.keys() & desktop[code].keys():
            raise ValueError(f"{code}: shared keys must be edited in the macOS catalog, not overridden")
        catalog.update(desktop[code])
        name = re.sub(r"[^A-Z0-9]", "_", code.upper())
        tables.append((code, name))
        # Python orders str by code point, which is Rust's UTF-8 byte order.
        lines.append(f"static {name}: &[(&str, &str)] = &[")
        lines.extend(f"    ({rust_string(key)}, {rust_string(value)})," for key, value in sorted(catalog.items()))
        lines.extend(["];", ""])
    lines.append("pub(crate) static TABLES: &[(&str, &[(&str, &str)])] = &[")
    lines.extend(f"    ({rust_string(code)}, {name})," for code, name in tables)
    lines.extend([
        "];", "",
        "pub fn lookup(locale: &str, key: &str) -> Option<&'static str> {",
        "    let (_, table) = TABLES.iter().find(|(code, _)| *code == locale)?;",
        "    table",
        "        .binary_search_by(|(candidate, _)| (*candidate).cmp(key))",
        "        .ok()",
        "        .map(|index| table[index].1)",
        "}", "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.exit(1, "Rust catalogs are stale. Run LinuxWindows/scripts/sync-localizations.py\n")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
