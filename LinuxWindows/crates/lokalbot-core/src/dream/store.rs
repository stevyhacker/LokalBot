//! Persistence for the overnight review (`DreamStore.swift`), inside the
//! library:
//!
//!   dreams/<yyyy-MM-dd>.json    the report; its presence marks the day reviewed
//!   dreams/<yyyy-MM-dd>.md      the same report, readable
//!   memory/memory.json          work memory
//!   memory/memory.md            the same memory, readable
//!
//! Every check-then-write runs under the advisory `.dream-store.lock`, which the
//! Mac takes too. Withdrawing changed evidence first records its intent in
//! `.dream-revocation-pending.json`: while that file exists nothing may read
//! overnight memory, so a failed cleanup can't leave old facts in use.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::Context as _;
use chrono::{DateTime, Utc};
use parking_lot::Mutex;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use super::rollup;
use super::{DreamMemory, DreamReport, MEMORY_VERSION, REPORT_VERSION};
use crate::evidence::{
    EVIDENCE_FILE, EvidenceState, MEMORY_FILE, PENDING_FILE, Provenance, StoreLock,
};
use crate::library::{read_json, write_atomic, write_json};

pub const GENERATED_MARKER: &str = "<!-- Generated by LokalBot dreaming. -->";
const MEMORY_MARKDOWN: &str = "memory/memory.md";

#[derive(Debug, thiserror::Error)]
pub enum StoreError {
    /// What this review read changed while it ran, so it must not be saved.
    #[error("The review was overtaken by a change to what it read.")]
    Cancelled,
    #[error(
        "Dream memory is unavailable because changed evidence could not be retracted. Retry after resolving the storage error."
    )]
    RetractionIncomplete,
    #[error(
        "Unsupported dream memory version {found}; this version of LokalBot supports version {supported}."
    )]
    UnsupportedMemoryVersion { found: i32, supported: i32 },
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

impl From<std::io::Error> for StoreError {
    fn from(err: std::io::Error) -> Self {
        Self::Other(err.into())
    }
}

pub type StoreResult<T> = Result<T, StoreError>;

/// A work-memory item the person can pin, by the merge's case-insensitive keys.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MemoryEntry {
    Project(String),
    Goal(String),
}

/// One revocation's durable intent, as the Mac writes it.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct PendingInvalidation {
    #[serde(default = "Uuid::new_v4", with = "crate::ids::uuid_upper_serde")]
    id: Uuid,
    #[serde(default)]
    days: BTreeSet<String>,
    /// Days whose screen, activity, coding-agent or digest evidence changed
    /// without touching a meeting.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    activity_days: Option<BTreeSet<String>>,
    #[serde(default)]
    meetings: BTreeSet<String>,
    #[serde(default)]
    reports: BTreeSet<String>,
    #[serde(default)]
    awaiting_source_mutation: bool,
    #[serde(
        default,
        rename = "ownerProcessID",
        skip_serializing_if = "Option::is_none"
    )]
    owner_process_id: Option<i32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    protected_by_mutation_lock: Option<bool>,
}

impl PendingInvalidation {
    fn merge(&mut self, other: &Self) {
        self.days.extend(other.days.iter().cloned());
        if let Some(activity) = &other.activity_days {
            self.activity_days
                .get_or_insert_with(BTreeSet::new)
                .extend(activity.iter().cloned());
        }
        self.meetings.extend(other.meetings.iter().cloned());
        self.reports.extend(other.reports.iter().cloned());
    }
}

/// Revocations this process couldn't finish. Nothing reads overnight memory for
/// these roots until a retry succeeds, even if the record itself couldn't be
/// written (`blockedRoots`, `pendingInvalidations`).
static BLOCKED: Mutex<Option<HashMap<PathBuf, PendingInvalidation>>> = Mutex::new(None);

pub(crate) fn is_blocked(root: &Path) -> bool {
    BLOCKED
        .lock()
        .as_ref()
        .is_some_and(|blocked| blocked.contains_key(root))
}

/// One change to withdraw.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Revocation {
    pub days: BTreeSet<String>,
    pub meetings: BTreeSet<String>,
    pub reports: BTreeSet<String>,
    pub activity_only: bool,
}

#[derive(Clone, Debug)]
pub struct DreamStore {
    root: PathBuf,
}

impl DreamStore {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    fn dreams_dir(&self) -> PathBuf {
        self.root.join("dreams")
    }

    pub fn report_path(&self, key: &str) -> PathBuf {
        self.dreams_dir().join(format!("{key}.json"))
    }

    fn report_markdown_path(&self, key: &str) -> PathBuf {
        self.dreams_dir().join(format!("{key}.md"))
    }

    fn pending_path(&self) -> PathBuf {
        self.root.join(PENDING_FILE)
    }

    // ---------------------------------------------------------------- state

    fn evidence_available(&self) -> bool {
        !is_blocked(&self.root) && !self.pending_path().exists()
    }

    fn require_available(&self) -> StoreResult<()> {
        if self.evidence_available() {
            Ok(())
        } else {
            Err(StoreError::RetractionIncomplete)
        }
    }

    fn state(&self) -> StoreResult<EvidenceState> {
        Ok(read_json(&self.root.join(EVIDENCE_FILE))?.unwrap_or_default())
    }

    fn intents(&self) -> StoreResult<Vec<PendingInvalidation>> {
        Ok(read_json(&self.pending_path())?.unwrap_or_default())
    }

    /// Capture this before compiling evidence, and require it when committing.
    /// A revocation left unfinished is finished first.
    pub fn evidence_revision(&self) -> StoreResult<u64> {
        let _lock = StoreLock::acquire(&self.root)?;
        let mut durable = self.intents()?;
        let mut recovered = false;
        for intent in &mut durable {
            if !intent.awaiting_source_mutation {
                continue;
            }
            // Holding the lock proves a lock-protected mutation is over. This
            // app only writes those, so an unprotected one is from a Mac run
            // that isn't this process, and its write can't be coming here.
            let ours = intent.owner_process_id == Some(std::process::id() as i32);
            if intent.protected_by_mutation_lock != Some(true) && ours {
                return Err(StoreError::RetractionIncomplete);
            }
            intent.awaiting_source_mutation = false;
            recovered = true;
        }
        if recovered {
            write_json(&self.pending_path(), &durable)?;
        }
        let in_memory = BLOCKED
            .lock()
            .as_ref()
            .and_then(|blocked| blocked.get(&self.root).cloned());
        if in_memory.is_some() || !durable.is_empty() {
            // Recovery treats activity-only days as day-wide: conservative.
            let mut merged = in_memory.unwrap_or_default();
            for intent in &durable {
                merged.merge(intent);
            }
            let mut days = merged.days;
            days.extend(merged.activity_days.unwrap_or_default());
            self.revoke_locked(
                &Revocation {
                    days,
                    meetings: merged.meetings,
                    reports: merged.reports,
                    activity_only: false,
                },
                Utc::now(),
            )?;
        }
        self.require_available()?;
        Ok(self.state()?.revision)
    }

    /// For evidence-backed data kept elsewhere (learned personal items): the
    /// current state, or `None` while a revocation is pending or the state
    /// can't be read, so callers withhold that data meanwhile.
    pub fn evidence_check(&self) -> Option<EvidenceState> {
        let _lock = StoreLock::acquire(&self.root).ok()?;
        if !self.evidence_available() {
            return None;
        }
        self.state().ok()
    }

    // -------------------------------------------------------------- reports

    fn invalidated(&self, provenance: Option<&Provenance>, state: &EvidenceState) -> bool {
        state.invalidates(provenance)
    }

    pub fn report(&self, key: &str) -> Option<DreamReport> {
        let _lock = StoreLock::acquire(&self.root).ok()?;
        if !self.evidence_available() {
            return None;
        }
        let state = self.state().ok()?;
        self.read_report_locked(key, &state)
    }

    fn read_report_locked(&self, key: &str, state: &EvidenceState) -> Option<DreamReport> {
        let report: DreamReport = read_json(&self.report_path(key)).ok().flatten()?;
        (report.day == key
            && (1..=REPORT_VERSION).contains(&report.version)
            && !self.invalidated(report.evidence_provenance.as_ref(), state))
        .then_some(report)
    }

    pub fn has_report(&self, key: &str) -> bool {
        self.report(key).is_some()
    }

    /// The newest valid report by reviewed day.
    pub fn latest_report(&self) -> Option<DreamReport> {
        let mut names: Vec<String> = fs::read_dir(self.dreams_dir())
            .ok()?
            .flatten()
            .filter_map(|entry| entry.file_name().to_str().map(str::to_string))
            .filter_map(|name| name.strip_suffix(".json").map(str::to_string))
            .collect();
        names.sort_unstable_by(|a, b| b.cmp(a));
        names.into_iter().find_map(|key| self.report(&key))
    }

    fn write_markdown(&self, body: &str, path: &Path) -> StoreResult<()> {
        write_atomic(path, format!("{GENERATED_MARKER}\n\n{body}\n").as_bytes())?;
        Ok(())
    }

    /// The JSON is the scheduler's completion marker, so its Markdown sibling is
    /// durable before the marker appears.
    fn write_report_locked(&self, report: &DreamReport) -> StoreResult<()> {
        self.write_markdown(&report.markdown(), &self.report_markdown_path(&report.day))?;
        write_json(&self.report_path(&report.day), report)?;
        Ok(())
    }

    pub fn save_report(&self, report: &DreamReport) -> StoreResult<()> {
        let _lock = StoreLock::acquire(&self.root)?;
        self.require_available()?;
        if self.invalidated(report.evidence_provenance.as_ref(), &self.state()?) {
            return Err(StoreError::Cancelled);
        }
        self.write_report_locked(report)
    }

    fn remove_report_locked(&self, key: &str) -> StoreResult<()> {
        for path in [self.report_path(key), self.report_markdown_path(key)] {
            remove_if_present(&path)?;
        }
        // Week and month lines drawn from this day go with it.
        rollup::remove_covering(key, &self.root);
        Ok(())
    }

    /// Removes a report so the scheduler rebuilds that day.
    pub fn invalidate_report(&self, key: &str) -> StoreResult<()> {
        let _lock = StoreLock::acquire(&self.root)?;
        self.remove_report_locked(key)
    }

    // --------------------------------------------------------------- memory

    fn memory_path(&self) -> PathBuf {
        self.root.join(MEMORY_FILE)
    }

    fn read_memory_locked(&self, state: &EvidenceState) -> StoreResult<Option<DreamMemory>> {
        let Some(memory): Option<DreamMemory> = read_json(&self.memory_path())? else {
            return Ok(None);
        };
        if !(1..=MEMORY_VERSION).contains(&memory.version) {
            return Err(StoreError::UnsupportedMemoryVersion {
                found: memory.version,
                supported: MEMORY_VERSION,
            });
        }
        Ok(Some(retracting(memory, state)))
    }

    fn write_memory_locked(&self, memory: &DreamMemory, state: &EvidenceState) -> StoreResult<()> {
        let mut memory = retracting(memory.clone(), state);
        memory.version = MEMORY_VERSION;
        write_json(&self.memory_path(), &memory)?;
        self.write_markdown(&memory.markdown(), &self.root.join(MEMORY_MARKDOWN))
    }

    pub fn load_memory(&self) -> StoreResult<Option<DreamMemory>> {
        let _lock = StoreLock::acquire(&self.root)?;
        if !self.evidence_available() {
            return Ok(None);
        }
        self.read_memory_locked(&self.state()?)
    }

    pub fn save_memory(&self, memory: &DreamMemory) -> StoreResult<()> {
        let _lock = StoreLock::acquire(&self.root)?;
        self.require_available()?;
        self.write_memory_locked(memory, &self.state()?)
    }

    /// Reloads before changing a pin, so a page can't overwrite memory a review
    /// wrote since it appeared. `None` when the entry no longer exists.
    pub fn set_pinned(
        &self,
        pinned: bool,
        entry: &MemoryEntry,
        at: DateTime<Utc>,
    ) -> StoreResult<Option<DreamMemory>> {
        let _lock = StoreLock::acquire(&self.root)?;
        if !self.evidence_available() {
            return Ok(None);
        }
        let state = self.state()?;
        let Some(mut memory) = self.read_memory_locked(&state)? else {
            return Ok(None);
        };
        match entry {
            MemoryEntry::Project(name) => {
                let Some(project) = memory
                    .active_projects
                    .iter_mut()
                    .find(|p| super::same_text(&p.name, name))
                else {
                    return Ok(None);
                };
                if project.pinned == pinned {
                    return Ok(Some(memory));
                }
                project.pinned = pinned;
            }
            MemoryEntry::Goal(text) => {
                let Some(goal) = memory
                    .work_goals
                    .iter_mut()
                    .find(|g| super::same_text(&g.text, text))
                else {
                    return Ok(None);
                };
                if goal.pinned == pinned {
                    return Ok(Some(memory));
                }
                goal.pinned = pinned;
            }
        }
        memory.updated_at = at;
        self.write_memory_locked(&memory, &state)?;
        Ok(Some(memory))
    }

    /// One whole review. Only the sources it read decide whether it is stale, so
    /// a change to another day's evidence doesn't discard the run. Memory is
    /// retracted against the current state as it is written, then the report,
    /// with its JSON marker last: an earlier failure leaves the day to retry.
    pub fn save_generated(
        &self,
        report: &DreamReport,
        memory: Option<&DreamMemory>,
        based_on_revision: u64,
    ) -> StoreResult<()> {
        let _lock = StoreLock::acquire(&self.root)?;
        self.require_available()?;
        let state = self.state()?;
        if state
            .memory_cleared_revision
            .is_some_and(|cleared| based_on_revision < cleared)
        {
            return Err(StoreError::Cancelled);
        }
        match &report.evidence_provenance {
            Some(provenance) => {
                if provenance.revision > based_on_revision
                    || self.invalidated(Some(provenance), &state)
                {
                    return Err(StoreError::Cancelled);
                }
            }
            None => {
                if state.revision != based_on_revision {
                    return Err(StoreError::Cancelled);
                }
            }
        }
        if let Some(memory) = memory {
            self.write_memory_locked(memory, &state)?;
        }
        self.write_report_locked(report)
    }

    /// Clear work memory: every report and the memory, pins included. Scheduled
    /// retention never removes them, so this and source deletion are how they go.
    pub fn clear_all(&self) -> StoreResult<()> {
        let _lock = StoreLock::acquire(&self.root)?;
        let mut state = self.state()?;
        state.revision += 1;
        state.memory_cleared_revision = Some(state.revision);
        write_json(&self.root.join(EVIDENCE_FILE), &state)?;
        let dreams = self.dreams_dir();
        if let Ok(entries) = fs::read_dir(&dreams) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_dir() {
                    fs::remove_dir_all(&path)
                        .with_context(|| format!("removing {}", path.display()))?;
                } else {
                    remove_if_present(&path)?;
                }
            }
        }
        remove_if_present(&self.memory_path())?;
        remove_if_present(&self.root.join(MEMORY_MARKDOWN))?;
        Ok(())
    }

    // ----------------------------------------------------------- revocation

    /// `DreamStore.invalidateEvidence`: the intent is durable before the state
    /// advances, and memory and reports are cleaned up after it. Returns the
    /// report days removed. Pins affect retention, never source revocation.
    pub fn invalidate_evidence(
        &self,
        revocation: &Revocation,
        at: DateTime<Utc>,
    ) -> StoreResult<BTreeSet<String>> {
        let _lock = StoreLock::acquire(&self.root)?;
        self.revoke_locked(revocation, at)
    }

    /// With the store lock held.
    pub(crate) fn revoke_locked(
        &self,
        revocation: &Revocation,
        at: DateTime<Utc>,
    ) -> StoreResult<BTreeSet<String>> {
        if revocation.days.is_empty() && revocation.meetings.is_empty() {
            return Ok(BTreeSet::new());
        }
        let mut pending = {
            let mut guard = BLOCKED.lock();
            guard
                .as_mut()
                .and_then(|blocked| blocked.remove(&self.root))
                .unwrap_or_default()
        };
        if revocation.activity_only && revocation.meetings.is_empty() {
            pending
                .activity_days
                .get_or_insert_with(BTreeSet::new)
                .extend(revocation.days.iter().cloned());
        } else {
            pending.days.extend(revocation.days.iter().cloned());
        }
        pending.meetings.extend(revocation.meetings.iter().cloned());
        pending.reports.extend(revocation.reports.iter().cloned());
        match self.commit_revocation(pending.clone(), at) {
            Ok(keys) => Ok(keys),
            Err(err) => {
                // Don't let another store read old facts or start a review.
                BLOCKED
                    .lock()
                    .get_or_insert_with(HashMap::new)
                    .insert(self.root.clone(), pending);
                Err(err)
            }
        }
    }

    fn commit_revocation(
        &self,
        mut pending: PendingInvalidation,
        at: DateTime<Utc>,
    ) -> StoreResult<BTreeSet<String>> {
        if pending.id.is_nil() {
            pending.id = Uuid::new_v4();
        }
        let mut intents = self.intents()?;
        for intent in &mut intents {
            let mut days = intent.days.clone();
            days.extend(intent.activity_days.clone().unwrap_or_default());
            let affected: BTreeSet<&String> = pending
                .days
                .iter()
                .chain(pending.activity_days.iter().flatten())
                .collect();
            let matches_completed = days.iter().all(|day| affected.contains(day))
                && intent.meetings.is_subset(&pending.meetings);
            if !intent.awaiting_source_mutation || matches_completed {
                intent.awaiting_source_mutation = false;
                pending.merge(intent);
            }
        }
        intents.push(pending.clone());
        // The intent precedes the state: a fresh process mustn't mistake a
        // failed state write for no change.
        write_json(&self.pending_path(), &intents)?;

        let mut state = self.state()?;
        if state.revision == u64::MAX {
            return Err(StoreError::RetractionIncomplete);
        }
        state.revision += 1;
        let revision = state.revision;
        for day in &pending.days {
            state.invalidated_days.insert(day.clone(), revision);
        }
        if let Some(activity) = pending.activity_days.as_ref().filter(|a| !a.is_empty()) {
            let map = state
                .invalidated_activity_days
                .get_or_insert_with(BTreeMap::new);
            for day in activity {
                map.insert(day.clone(), revision);
            }
        }
        let meetings = state.invalidated_meetings.get_or_insert_with(BTreeMap::new);
        for id in &pending.meetings {
            meetings.insert(id.to_uppercase(), revision);
        }
        write_json(&self.root.join(EVIDENCE_FILE), &state)?;

        // A file this version can't decode stays as it is: every reader filters
        // it by the state just written, and it mustn't stop a deletion.
        match self.read_memory_locked(&state) {
            Ok(Some(mut memory)) => {
                memory.updated_at = at;
                self.write_memory_locked(&memory, &state)?;
            }
            Ok(None) => {}
            Err(err) => log::warn!("work memory left as it is: {err:#}"),
        }
        let mut keys = pending.reports.clone();
        if let Ok(entries) = fs::read_dir(self.dreams_dir()) {
            for entry in entries.flatten() {
                let name = entry.file_name();
                let Some(key) = name.to_str().and_then(|n| n.strip_suffix(".json")) else {
                    continue;
                };
                if let Some(report) = read_json::<DreamReport>(&self.report_path(key))
                    .ok()
                    .flatten()
                    && self.invalidated(report.evidence_provenance.as_ref(), &state)
                {
                    keys.insert(key.to_string());
                }
            }
        }
        for key in &keys {
            self.remove_report_locked(key)?;
        }
        let remaining: Vec<&PendingInvalidation> = intents
            .iter()
            .filter(|i| i.awaiting_source_mutation)
            .collect();
        if remaining.is_empty() {
            remove_if_present(&self.pending_path())?;
        } else {
            write_json(&self.pending_path(), &remaining)?;
        }
        Ok(keys)
    }
}

/// `DreamMemory.retractingEvidence`. Source revocation overrides pinning, and an
/// item without provenance goes with the first change rather than guessing.
fn retracting(mut memory: DreamMemory, state: &EvidenceState) -> DreamMemory {
    if state.revision == 0 {
        return memory;
    }
    memory
        .active_projects
        .retain(|p| !state.invalidates(p.provenance.as_ref()));
    memory
        .work_goals
        .retain(|g| !state.invalidates(g.provenance.as_ref()));
    let provenance = memory.pattern_provenance.clone();
    memory
        .recurring_patterns
        .retain(|p| !state.invalidates(provenance.get(p)));
    let remaining: BTreeSet<String> = memory.recurring_patterns.iter().cloned().collect();
    memory
        .pattern_provenance
        .retain(|pattern, _| remaining.contains(pattern));
    memory
}

fn remove_if_present(path: &Path) -> StoreResult<()> {
    match fs::remove_file(path) {
        Err(err) if err.kind() != std::io::ErrorKind::NotFound => Err(StoreError::Other(
            anyhow::Error::from(err).context(format!("removing {}", path.display())),
        )),
        _ => Ok(()),
    }
}
