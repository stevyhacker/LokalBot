use super::registry::SettingKind::*;
use super::registry::SettingTier::*;
use super::registry::{
    SettingCategory, SettingChoice, SettingKind, SettingSpec, SettingTier, Stored, TextFormat,
};

macro_rules! c {
    ($token:literal) => {
        SettingChoice {
            token: $token,
            stored: Stored::Text($token),
        }
    };
    ($token:literal, $stored:literal) => {
        SettingChoice {
            token: $token,
            stored: Stored::Text($stored),
        }
    };
}

macro_rules! n {
    ($token:literal, $stored:expr) => {
        SettingChoice {
            token: $token,
            stored: Stored::Integer($stored),
        }
    };
}

