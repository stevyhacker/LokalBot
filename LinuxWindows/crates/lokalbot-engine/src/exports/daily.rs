//! The optional daily Markdown note (`DailyMemoryExportService.swift`): one
//! deterministic file per day with the digest, meeting links, app time and saved
//! moments. A hidden sidecar records the hash of the exact bytes LokalBot wrote,
//! so a person's edit is never overwritten.

use std::path::{Path, PathBuf};

use anyhow::Result;
use chrono::{DateTime, Local, NaiveDate, Utc};
use lokalbot_core::Library;
use lokalbot_core::day_stats::{AppTime, DaySummary, SavedMoment};
use lokalbot_core::generated_file::{self, WriteError};
use lokalbot_core::settings::DailyMemoryExportFormat;
use lokalbot_core::time::local_day_bounds;

use super::single_line;

pub const GENERATED_FILE_MARKER: &str = "<!-- Generated by LokalBot daily memory export. -->";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Pass {
    /// Writes or refreshes the day's note.
    Refresh,
    /// A past day the export missed, because the computer was asleep or off at
    /// the export hour. Written only if the folder has no file for that day and
    /// something was recorded.
    CatchUp,
}

#[derive(Debug, thiserror::Error)]
pub enum ExportError {
    #[error(
        "Daily memory export stopped because {0} already exists and was not generated by LokalBot. Choose another folder or move that file."
    )]
    DestinationCollision(String),
    #[error(
        "Daily memory export stopped because {0} was edited after LokalBot generated it. Your edits were preserved; move the file or choose another export folder to resume automatic refreshes."
    )]
    GeneratedFileModified(String),
    #[error(transparent)]
    Io(#[from] std::io::Error),
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

#[derive(Clone, Debug, PartialEq)]
pub struct MeetingReference {
    pub id: String,
    pub title: String,
    pub started_at: DateTime<Utc>,
    pub duration_seconds: f64,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Snapshot {
    pub day: NaiveDate,
    pub digest: Option<String>,
    /// A digest exists but no longer matches the day's evidence, so it is left
    /// out until the digest is updated.
    pub digest_is_out_of_date: bool,
    pub meetings: Vec<MeetingReference>,
    pub saved_moments: Vec<SavedMoment>,
    pub stats: DaySummary,
    pub app_usage: Vec<AppTime>,
}

impl Snapshot {
    pub fn is_empty(&self) -> bool {
        self.digest.is_none()
            && self.meetings.is_empty()
            && self.saved_moments.is_empty()
            && self.app_usage.is_empty()
            && self.stats.tracked_seconds == 0.0
            && self.stats.screenshot_count == 0
    }
}

pub fn snapshot(library: &Library, day: NaiveDate) -> Result<Snapshot> {
    let (start, end) = local_day_bounds(day);
    // The sample meeting is made up: it never becomes part of the day.
    let mut meetings: Vec<_> = library
        .list_meetings()?
        .into_iter()
        .filter(|m| !m.is_sample() && m.started_at >= start && m.started_at < end)
        .collect();
    meetings.sort_by_key(|meeting| meeting.started_at);
    let digest = lokalbot_ai::digest::generated_digest(library, day);
    Ok(Snapshot {
        day,
        digest: digest
            .as_ref()
            .filter(|(_, current)| *current)
            .map(|(text, _)| text.clone()),
        digest_is_out_of_date: digest.is_some_and(|(_, current)| !current),
        meetings: meetings
            .iter()
            .map(|meeting| MeetingReference {
                id: meeting.short_id(),
                title: meeting.title.clone(),
                started_at: meeting.started_at,
                duration_seconds: meeting.duration_seconds(),
            })
            .collect(),
        saved_moments: library.saved_moments_between(start, end, 500)?,
        stats: library.day_summary(start, end)?,
        app_usage: library.app_time(start, end, 100)?,
    })
}

#[derive(Debug, PartialEq, Eq)]
pub enum Outcome {
    Written(PathBuf),
    Unchanged(PathBuf),
    /// A catch-up found a file already there, or nothing recorded.
    Skipped,
}

fn file_name(day: NaiveDate, format: DailyMemoryExportFormat) -> String {
    match format {
        DailyMemoryExportFormat::Logseq => day.format("%Y_%m_%d.md").to_string(),
        _ => day.format("%Y-%m-%d.md").to_string(),
    }
}

/// Rewrites one deterministic day file. Identical content keeps its modified
/// time; changed app-owned content is replaced atomically.
pub fn export(
    library: &Library,
    day: NaiveDate,
    destination: &Path,
    format: DailyMemoryExportFormat,
    pass: Pass,
) -> Result<Outcome, ExportError> {
    let path = destination.join(file_name(day, format));
    if pass == Pass::CatchUp && path.exists() {
        return Ok(Outcome::Skipped);
    }
    let snapshot = snapshot(library, day)?;
    if pass == Pass::CatchUp && snapshot.is_empty() {
        return Ok(Outcome::Skipped);
    }
    let text = render(&snapshot, format);
    std::fs::create_dir_all(destination)?;
    let name = || {
        path.file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default()
    };
    match generated_file::write(text.as_bytes(), &path, GENERATED_FILE_MARKER) {
        Ok(true) => Ok(Outcome::Written(path)),
        Ok(false) => Ok(Outcome::Unchanged(path)),
        Err(WriteError::Collision) => Err(ExportError::DestinationCollision(name())),
        Err(WriteError::Io(err)) => Err(ExportError::Io(err)),
        Err(_) => Err(ExportError::GeneratedFileModified(name())),
    }
}

fn time(at: DateTime<Utc>) -> String {
    at.with_timezone(&Local).format("%H:%M").to_string()
}

fn duration(seconds: f64) -> String {
    let minutes = (seconds.round() as i64 / 60).max(0);
    if minutes >= 60 {
        format!("{}h {}m", minutes / 60, minutes % 60)
    } else {
        format!("{minutes}m")
    }
}

pub fn render(snapshot: &Snapshot, format: DailyMemoryExportFormat) -> String {
    let key = snapshot.day.format("%Y-%m-%d");
    let display = snapshot.day.format("%B %-d, %Y");
    let heading = format!("{GENERATED_FILE_MARKER}\n\n# Daily memory — {display}");
    let opening = match format {
        DailyMemoryExportFormat::Markdown => heading,
        DailyMemoryExportFormat::Obsidian => format!(
            "---\ndate: {key}\ntags:\n  - lokalbot/daily-memory\nsource: LokalBot\n---\n\n{heading}"
        ),
        DailyMemoryExportFormat::Logseq => format!(
            "title:: Daily memory — {display}\ndate:: {key}\ntags:: lokalbot, daily-memory\n\n{heading}"
        ),
    };
    let digest = snapshot
        .digest
        .as_deref()
        .map(str::trim)
        .filter(|digest| !digest.is_empty());
    let missing_digest = if snapshot.digest_is_out_of_date {
        "_The day's digest is out of date. It is added here once it is updated._"
    } else {
        "_No day digest was generated._"
    };
    [
        opening,
        format!("## Digest\n\n{}", digest.unwrap_or(missing_digest)),
        meetings_section(&snapshot.meetings),
        saved_moments_section(&snapshot.saved_moments),
        stats_section(snapshot),
    ]
    .join("\n\n")
        + "\n"
}

fn meetings_section(meetings: &[MeetingReference]) -> String {
    if meetings.is_empty() {
        return "## Meetings\n\n_No meetings._".into();
    }
    let rows: Vec<String> = meetings
        .iter()
        .map(|meeting| {
            format!(
                "- **{}** — {} · {} (`{}`)",
                time(meeting.started_at),
                inline(&meeting.title),
                duration(meeting.duration_seconds),
                meeting.id
            )
        })
        .collect();
    format!("## Meetings\n\n{}", rows.join("\n"))
}

fn saved_moments_section(moments: &[SavedMoment]) -> String {
    if moments.is_empty() {
        return "## Saved moments\n\n_No saved moments._".into();
    }
    let rows: Vec<String> = moments
        .iter()
        .map(|moment| {
            let title = if moment.window_title.is_empty() {
                inline(&moment.app)
            } else {
                format!("{} — {}", inline(&moment.app), inline(&moment.window_title))
            };
            let mut lines = vec![format!(
                "- **{}** — {title} (`screen:{}`)",
                time(moment.captured_at),
                moment.snapshot_id
            )];
            let note = single_line(&moment.note);
            if !note.is_empty() {
                lines.push(format!("  - Note: {}", inline(&note)));
            }
            let excerpt = single_line(&moment.ocr_excerpt);
            if !excerpt.is_empty() {
                lines.push(format!("  - OCR: {}", inline(&excerpt)));
            }
            lines.join("\n")
        })
        .collect();
    format!("## Saved moments\n\n{}", rows.join("\n"))
}

fn stats_section(snapshot: &Snapshot) -> String {
    let stats = &snapshot.stats;
    let mut lines = vec![
        "## Day stats".to_string(),
        String::new(),
        "| Metric | Value |".to_string(),
        "| --- | ---: |".to_string(),
        format!("| Tracked time | {} |", duration(stats.tracked_seconds)),
        format!("| Apps | {} |", stats.app_count),
        format!("| Activity blocks | {} |", stats.activity_block_count),
        format!("| Screenshots | {} |", stats.screenshot_count),
        format!("| Saved moments | {} |", stats.saved_moment_count),
        format!("| Meetings | {} |", snapshot.meetings.len()),
    ];
    if !snapshot.app_usage.is_empty() {
        lines.extend([String::new(), "### App usage".to_string(), String::new()]);
        lines.extend(snapshot.app_usage.iter().map(|usage| {
            format!(
                "- {}: {}",
                inline(&usage.app),
                duration(usage.duration_seconds)
            )
        }));
    }
    lines.join("\n")
}

/// Unlike a meeting note's, this keeps a value's own spacing.
fn inline(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace('*', "\\*")
        .replace('_', "\\_")
        .replace('[', "\\[")
        .replace(']', "\\]")
        .replace('|', "\\|")
}
