//! Optional one-note-per-meeting export to a folder the person picks, such as an
//! Obsidian vault or a Logseq graph's `pages` folder (`MeetingNoteExportService`):
//! the summary with the action list as LokalBot shows it, people and tracked
//! projects as links, and optionally the transcript.
//!
//! A note is named when it is first written and keeps that name, so links to it
//! from other notes survive a renamed meeting. It is refreshed only while it
//! still holds the bytes LokalBot wrote. A note the person edited, deleted or
//! moved is theirs: LokalBot leaves it alone and does not write that meeting
//! again. Deleting a meeting in LokalBot leaves its note in place.

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

use anyhow::{Result, bail};
use chrono::{DateTime, Local, Utc};
use lokalbot_core::generated_file::{self, SIDECAR_SUFFIX, WriteError};
use lokalbot_core::library::sha256_hex;
use lokalbot_core::people::{PeopleInput, build_people};
use lokalbot_core::projects::{matches_words, significant_terms, words};
use lokalbot_core::settings::ExportFormat;
use lokalbot_core::{ActionItem, ActionStatus, Library, Meeting};
use uuid::Uuid;

use super::{inline, single_line};

pub const GENERATED_FILE_MARKER: &str = "<!-- Generated by LokalBot meeting note export. -->";
/// Part of every fingerprint: changing how notes look refreshes them all.
const RENDER_VERSION: &str = "1";
const FORBIDDEN_NAME_CHARACTERS: &str = "\\/:*?\"<>|#^[]";
const TITLE_CHARACTERS: usize = 80;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Configuration {
    pub destination: PathBuf,
    pub format: ExportFormat,
    pub includes_transcript: bool,
}

/// What one pass did. Fingerprints are of each meeting's sources, so the next
/// pass renders only the meetings whose notes could have changed.
#[derive(Debug, Default)]
pub struct Report {
    pub fingerprints: HashMap<Uuid, String>,
    pub written: Vec<PathBuf>,
    /// Meetings whose note could not be written, tried again on a later pass.
    pub failures: Vec<String>,
}

#[derive(Debug, PartialEq, Eq)]
pub enum Outcome {
    Written(PathBuf),
    Unchanged(PathBuf),
    /// Edited, deleted or moved by the person, or a file LokalBot did not write
    /// holds the name.
    Left,
}

/// Everything one note shows, read from the library.
#[derive(Clone, Debug)]
pub struct Note {
    pub meeting: Meeting,
    pub people: Vec<String>,
    pub projects: Vec<String>,
    pub summary: Option<String>,
    pub actions: Vec<lokalbot_core::ActionReference>,
    pub transcript: Option<String>,
}

fn format_key(format: ExportFormat) -> &'static str {
    match format {
        ExportFormat::Markdown => "Markdown",
        ExportFormat::Obsidian => "Obsidian",
        ExportFormat::Logseq => "Logseq",
    }
}

/// `ContentFingerprint.fields`: SHA-256 over `<byte length>:<bytes>` per field.
fn fingerprint(fields: &[&str]) -> String {
    let mut material = Vec::new();
    for field in fields {
        material.extend(format!("{}:", field.len()).as_bytes());
        material.extend(field.as_bytes());
    }
    sha256_hex(&material)
}

/// Writes or refreshes the note of every finished meeting with a summary, or a
/// transcript when transcripts are included. A meeting whose fingerprint matches
/// `previous` is skipped without being read.
pub fn export(
    library: &Library,
    configuration: &Configuration,
    previous: &HashMap<Uuid, String>,
    is_cancelled: &dyn Fn() -> bool,
) -> Result<Report> {
    // The sample meeting is made up, so it never lands in the person's notes.
    let meetings: Vec<Meeting> = library
        .list_meetings()?
        .into_iter()
        .filter(|meeting| !meeting.is_sample())
        .collect();
    std::fs::create_dir_all(&configuration.destination)?;
    let existing = ExistingNotes::read(&configuration.destination)?;

    // Sources are stamped before anything is read from them: a file that changes
    // after its stamp is taken changes the next pass's stamp too.
    let mut stamps: HashMap<Uuid, String> = HashMap::new();
    for meeting in meetings.iter().filter(|m| m.ended_at.is_some()) {
        let folder = library.meeting_dir(meeting);
        let has_summary = folder.join("summary.md").exists();
        let has_transcript = folder.join("transcript.md").exists();
        if has_summary || (has_transcript && configuration.includes_transcript) {
            stamps.insert(meeting.id, source_stamp(&folder));
        }
    }
    let connections = Connections::read(library, &meetings);
    let configuration_key = format!(
        "{}|{}",
        format_key(configuration.format),
        configuration.includes_transcript
    );

    let mut report = Report::default();
    for meeting in &meetings {
        let Some(stamp) = stamps.get(&meeting.id) else {
            continue;
        };
        if is_cancelled() {
            bail!("cancelled");
        }
        let people = connections
            .people
            .get(&meeting.id)
            .cloned()
            .unwrap_or_default();
        let note_fingerprint = fingerprint(&[
            RENDER_VERSION,
            &configuration_key,
            stamp,
            &people.join("\n"),
            &connections.projects_key,
        ]);
        if previous.get(&meeting.id) == Some(&note_fingerprint) {
            report.fingerprints.insert(meeting.id, note_fingerprint);
            continue;
        }
        let note = load_note(library, meeting, people, &connections, configuration);
        match write_note(&note, configuration, &existing) {
            Ok(outcome) => {
                report.fingerprints.insert(meeting.id, note_fingerprint);
                if let Outcome::Written(path) = outcome {
                    report.written.push(path);
                }
            }
            Err(err) => {
                log::warn!(
                    "meeting note export failed for {}: {err}",
                    meeting.short_id()
                );
                report
                    .failures
                    .push(format!("{}: {err}", meeting.display_title()));
            }
        }
    }
    Ok(report)
}

pub fn write_note(
    note: &Note,
    configuration: &Configuration,
    existing: &ExistingNotes,
) -> std::io::Result<Outcome> {
    let short_id = note.meeting.short_id();
    let name = if let Some(current) = existing.names.get(&short_id) {
        current.clone()
    } else if existing.removed.contains(&short_id) {
        return Ok(Outcome::Left);
    } else {
        file_name(&note.meeting)
    };
    let path = configuration.destination.join(name);
    let data = render(note, configuration.format);
    match generated_file::write(data.as_bytes(), &path, GENERATED_FILE_MARKER) {
        Ok(true) => Ok(Outcome::Written(path)),
        Ok(false) => Ok(Outcome::Unchanged(path)),
        Err(WriteError::Io(err)) => Err(err),
        Err(_) => Ok(Outcome::Left),
    }
}

fn contents(path: &Path) -> Option<String> {
    let text = std::fs::read_to_string(path).ok()?;
    let trimmed = text.trim();
    (!trimmed.is_empty()).then(|| trimmed.to_string())
}

fn load_note(
    library: &Library,
    meeting: &Meeting,
    people: Vec<String>,
    connections: &Connections,
    configuration: &Configuration,
) -> Note {
    let folder = library.meeting_dir(meeting);
    let summary = contents(&folder.join("summary.md"));
    let transcript = contents(&folder.join("transcript.md"));
    let projection = library.outcome_projection(meeting).ok().flatten();
    let actions = projection
        .as_ref()
        .map(|p| p.action_references())
        .unwrap_or_default();
    let mut texts = vec![summary.clone().unwrap_or_default()];
    texts.extend(actions.iter().map(|action| action.text.clone()));
    if let Some(projection) = &projection {
        texts.extend(
            projection
                .outcomes
                .decision_records
                .iter()
                .map(|decision| decision.text.clone()),
        );
    }
    let projects = connections.projects(meeting, &texts, transcript.as_deref());
    Note {
        meeting: meeting.clone(),
        people,
        projects,
        summary,
        actions,
        transcript: configuration
            .includes_transcript
            .then_some(transcript)
            .flatten(),
    }
}

fn yaml_string(value: &str) -> String {
    let mut escaped = String::new();
    for c in single_line(value).chars() {
        match c {
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            c if c.is_control() => escaped.push(' '),
            c => escaped.push(c),
        }
    }
    format!("\"{escaped}\"")
}

/// An Obsidian or Logseq link, without the characters that end one.
fn link(name: &str) -> Option<String> {
    let target: String = name.chars().filter(|c| !"[]|#^".contains(*c)).collect();
    let target = single_line(&target);
    (!target.is_empty()).then(|| format!("[[{target}]]"))
}

fn local(at: DateTime<Utc>) -> DateTime<Local> {
    at.with_timezone(&Local)
}

fn day_key(at: DateTime<Utc>) -> String {
    local(at).format("%Y-%m-%d").to_string()
}

pub fn render(note: &Note, format: ExportFormat) -> String {
    let meeting = &note.meeting;
    let title = single_line(&meeting.display_title());
    let short_id = meeting.short_id();
    let start = local(meeting.started_at).format("%H:%M").to_string();
    let duration = lokalbot_core::time::meeting_duration_label(meeting.duration_seconds());
    let people_links: Vec<String> = note.people.iter().filter_map(|p| link(p)).collect();
    let project_links: Vec<String> = note.projects.iter().filter_map(|p| link(p)).collect();
    let mut sections: Vec<String> = Vec::new();
    let heading = format!("{GENERATED_FILE_MARKER}\n\n# {}", inline(&title));
    match format {
        ExportFormat::Markdown => {
            let mut facts = vec![
                format!(
                    "- **When:** {}, {start} · {duration}",
                    local(meeting.started_at).format("%B %-d, %Y")
                ),
                format!("- **App:** {}", inline(&meeting.app_name)),
            ];
            if !note.people.is_empty() {
                let names: Vec<String> = note.people.iter().map(|p| inline(p)).collect();
                facts.push(format!("- **People:** {}", names.join(", ")));
            }
            if !note.projects.is_empty() {
                let names: Vec<String> = note.projects.iter().map(|p| inline(p)).collect();
                facts.push(format!("- **Projects:** {}", names.join(", ")));
            }
            facts.push(format!("- **Meeting:** `{short_id}`"));
            sections.push(heading);
            sections.push(facts.join("\n"));
        }
        ExportFormat::Obsidian => {
            let mut lines = vec![
                "---".to_string(),
                "aliases:".to_string(),
                format!("  - {}", yaml_string(&title)),
                format!("date: {}", day_key(meeting.started_at)),
                format!("time: {}", yaml_string(&start)),
                format!("duration: {}", yaml_string(&duration)),
                format!("app: {}", yaml_string(&meeting.app_name)),
            ];
            if !people_links.is_empty() {
                lines.push("people:".into());
                lines.extend(
                    people_links
                        .iter()
                        .map(|l| format!("  - {}", yaml_string(l))),
                );
            }
            if !project_links.is_empty() {
                lines.push("projects:".into());
                lines.extend(
                    project_links
                        .iter()
                        .map(|l| format!("  - {}", yaml_string(l))),
                );
            }
            lines.extend([
                "tags:".to_string(),
                "  - lokalbot/meeting".to_string(),
                format!("lokalbot-id: {}", yaml_string(&short_id)),
                "source: LokalBot".to_string(),
                "---".to_string(),
            ]);
            sections.push(lines.join("\n"));
            sections.push(heading);
        }
        ExportFormat::Logseq => {
            let mut lines = vec![format!("date:: {}", day_key(meeting.started_at))];
            if !people_links.is_empty() {
                lines.push(format!("people:: {}", people_links.join(", ")));
            }
            if !project_links.is_empty() {
                lines.push(format!("projects:: {}", project_links.join(", ")));
            }
            lines.extend([
                "tags:: lokalbot, meeting".to_string(),
                format!("lokalbot-id:: {short_id}"),
                "source:: LokalBot".to_string(),
            ]);
            sections.push(lines.join("\n"));
            sections.push(heading);
            sections.push(format!(
                "{start} · {duration} · {}",
                inline(&meeting.app_name)
            ));
        }
    }

    let actions = (!note.actions.is_empty()).then(|| action_lines(&note.actions, format));
    if let Some(summary) = &note.summary {
        let body = actions.as_ref().map_or_else(
            || summary.clone(),
            |lines| lokalbot_core::actions::replace_action_lines(summary, lines),
        );
        sections.push(lokalbot_ai::sanitize::redact(body.trim()));
    } else if let Some(actions) = &actions {
        let mut lines = vec!["## Action items".to_string(), String::new()];
        lines.extend_from_slice(actions);
        sections.push(lokalbot_ai::sanitize::redact(&lines.join("\n")));
    }
    if let Some(transcript) = &note.transcript {
        sections.push(format!(
            "## Transcript\n\n{}",
            lokalbot_ai::sanitize::redact(transcript)
        ));
    }
    sections.join("\n\n") + "\n"
}

/// The action list as LokalBot shows it, grouped like `summary.md`, with the
/// person's corrections applied and completed actions checked off.
pub fn action_lines(
    actions: &[lokalbot_core::ActionReference],
    format: ExportFormat,
) -> Vec<String> {
    let items: Vec<(ActionItem, ActionStatus)> = actions
        .iter()
        .map(|action| (action.effective_action(), action.status))
        .collect();
    let list = |group: Vec<&(ActionItem, ActionStatus)>, include_owner: bool| -> Vec<String> {
        if group.is_empty() {
            return vec!["None".to_string()];
        }
        group
            .into_iter()
            .map(|(action, status)| {
                let marker = match (format, status) {
                    (ExportFormat::Logseq, ActionStatus::Done) => "- DONE",
                    (ExportFormat::Logseq, _) => "- TODO",
                    (_, ActionStatus::Done) => "- [x]",
                    _ => "- [ ]",
                };
                let owner = if include_owner {
                    format!(
                        "{}: ",
                        single_line(action.owner.as_deref().unwrap_or("Owner not stated"))
                    )
                } else {
                    String::new()
                };
                let due = action
                    .due
                    .as_deref()
                    .map(|due| format!(" — due {}", single_line(due)))
                    .unwrap_or_default();
                let deferred = if *status == ActionStatus::Deferred {
                    " — deferred"
                } else {
                    ""
                };
                let citation = action
                    .citations
                    .iter()
                    .map(|citation| citation.start)
                    .min_by(f64::total_cmp)
                    .map(|start| format!(" — [{}]", lokalbot_core::time::stamp(start)))
                    .unwrap_or_default();
                format!(
                    "{marker} {owner}{}{due}{deferred}{citation}",
                    single_line(&action.display_text())
                )
            })
            .collect()
    };
    let mut lines = vec!["### Me".to_string()];
    lines.extend(list(
        items.iter().filter(|(a, _)| a.is_for_user).collect(),
        false,
    ));
    lines.extend([String::new(), "### Others".to_string()]);
    lines.extend(list(
        items
            .iter()
            .filter(|(a, _)| !a.is_for_user && !a.ownership_is_unclear())
            .collect(),
        true,
    ));
    let unclear: Vec<&(ActionItem, ActionStatus)> = items
        .iter()
        .filter(|(a, _)| a.ownership_is_unclear())
        .collect();
    if !unclear.is_empty() {
        lines.extend([String::new(), "### Owner unclear".to_string()]);
        lines.extend(list(unclear, false));
    }
    lines
}

/// "2026-09-29 Atlas release sync (4f7c2a91).md": the date sorts notes, the title
/// reads well in a vault, and the meeting's short id finds the note again after
/// the meeting is renamed.
pub fn file_name(meeting: &Meeting) -> String {
    let cleaned: String = meeting
        .display_title()
        .chars()
        .map(|c| {
            if FORBIDDEN_NAME_CHARACTERS.contains(c) || c.is_control() {
                ' '
            } else {
                c
            }
        })
        .collect();
    let line = single_line(&cleaned);
    let title: String = line
        .trim_start_matches('.')
        .chars()
        .take(TITLE_CHARACTERS)
        .collect();
    let title = title.trim_end();
    let shown = if title.is_empty() { "Meeting" } else { title };
    format!(
        "{} {shown} ({}).md",
        day_key(meeting.started_at),
        meeting.short_id()
    )
}

/// The meeting short id in a note name from [`file_name`].
pub fn meeting_id_in_file_name(name: &str) -> Option<String> {
    let body = name.strip_suffix(").md")?;
    let (_, id) = body.rsplit_once(" (")?;
    (id.len() == 8 && id.chars().all(|c| "0123456789abcdef".contains(c))).then(|| id.to_string())
}

/// Names, sizes and modification dates of the files in a meeting folder.
/// Processing, a correction, a completed action and a renamed speaker or meeting
/// each rewrite one of them.
pub fn source_stamp(folder: &Path) -> String {
    let Ok(entries) = std::fs::read_dir(folder) else {
        return String::new();
    };
    let mut lines: Vec<String> = entries
        .flatten()
        .filter_map(|entry| {
            let metadata = entry.metadata().ok()?;
            if !metadata.is_file() {
                return None;
            }
            let modified = metadata
                .modified()
                .ok()
                .map(DateTime::<Utc>::from)
                .map_or(0.0, lokalbot_core::time::to_epoch);
            Some(format!(
                "{}:{}:{modified}",
                entry.file_name().to_string_lossy(),
                metadata.len()
            ))
        })
        .collect();
    lines.sort();
    lines.join("\n")
}

/// The export folder's notes by meeting short id, and the meetings whose note is
/// gone while its ownership sidecar remains: the person deleted the note or moved
/// it elsewhere in the vault.
#[derive(Debug, Default, PartialEq)]
pub struct ExistingNotes {
    pub names: HashMap<String, String>,
    pub removed: HashSet<String>,
}

impl ExistingNotes {
    pub fn read(directory: &Path) -> std::io::Result<Self> {
        let mut entries: Vec<String> = std::fs::read_dir(directory)?
            .flatten()
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect();
        entries.sort();
        let present: HashSet<&str> = entries.iter().map(String::as_str).collect();
        let mut notes = Self::default();
        let mut owned: HashSet<String> = HashSet::new();
        for entry in &entries {
            let Some(note) = entry
                .strip_prefix('.')
                .and_then(|rest| rest.strip_suffix(SIDECAR_SUFFIX))
            else {
                continue;
            };
            let Some(id) = meeting_id_in_file_name(note) else {
                continue;
            };
            if present.contains(note) {
                owned.insert(note.to_string());
            } else {
                notes.removed.insert(id);
            }
        }
        for entry in entries.iter().filter(|entry| !entry.starts_with('.')) {
            let Some(id) = meeting_id_in_file_name(entry) else {
                continue;
            };
            // Two notes for one meeting: keep to the one LokalBot wrote.
            if let Some(current) = notes.names.get(&id)
                && (owned.contains(current) || !owned.contains(entry))
            {
                continue;
            }
            notes.names.insert(id, entry.clone());
        }
        let names: Vec<String> = notes.names.keys().cloned().collect();
        for id in names {
            notes.removed.remove(&id);
        }
        Ok(notes)
    }
}

/// People and tracked projects per meeting, joined with the same rules as the
/// People and Projects pages, once per pass.
struct Connections {
    people: HashMap<Uuid, Vec<String>>,
    tracked: Vec<(String, Vec<HashSet<String>>)>,
    /// Changes when a project is tracked, renamed or dropped, so every note's
    /// project links are looked at again.
    projects_key: String,
}

impl Connections {
    fn read(library: &Library, meetings: &[Meeting]) -> Self {
        let projections: Vec<_> = meetings
            .iter()
            .filter_map(|meeting| library.outcome_projection(meeting).ok().flatten())
            .collect();
        let profiles = build_people(&PeopleInput {
            meetings,
            projections: &projections,
            applied: &library.applied_names(meetings),
            self_names: &library.self_names(),
            curation: &library.people_curation().unwrap_or_default(),
            today: Local::now().date_naive(),
        });
        let mut people: HashMap<Uuid, Vec<String>> = HashMap::new();
        for profile in profiles {
            for meeting in &profile.meetings {
                people
                    .entry(meeting.id)
                    .or_default()
                    .push(profile.name.clone());
            }
        }
        for names in people.values_mut() {
            names.sort();
        }
        let curation = library.project_curation().unwrap_or_default();
        let all_names = |name: &str, others: &[String]| -> Vec<String> {
            std::iter::once(name.to_string())
                .chain(others.iter().cloned())
                .collect()
        };
        let tracked = curation
            .tracked
            .iter()
            .map(|project| {
                (
                    project.name.clone(),
                    all_names(&project.name, &project.other_names)
                        .iter()
                        .map(|name| significant_terms(name))
                        .collect(),
                )
            })
            .collect();
        let projects_key = curation
            .tracked
            .iter()
            .map(|project| all_names(&project.name, &project.other_names).join("\t"))
            .collect::<Vec<_>>()
            .join("\n");
        Self {
            people,
            tracked,
            projects_key,
        }
    }

    /// Tracked projects named in the meeting's title, notes, outcomes or
    /// transcript, as on the Projects page.
    fn projects(
        &self,
        meeting: &Meeting,
        texts: &[String],
        transcript: Option<&str>,
    ) -> Vec<String> {
        if self.tracked.is_empty() {
            return Vec::new();
        }
        let mut all = words(&meeting.display_title());
        all.extend(words(meeting.calendar_title.as_deref().unwrap_or("")));
        for text in texts {
            all.extend(words(text));
        }
        if let Some(transcript) = transcript {
            all.extend(transcript_words(transcript));
        }
        self.tracked
            .iter()
            .filter(|(_, terms)| matches_words(terms, &all))
            .map(|(name, _)| name.clone())
            .collect()
    }
}

/// `**[HH:MM:SS] Name:** text` lines count only for what was said.
fn transcript_words(markdown: &str) -> HashSet<String> {
    markdown
        .lines()
        .flat_map(|line| {
            let spoken = line
                .trim()
                .strip_prefix("**[")
                .and_then(|rest| rest.split_once(":**"))
                .map_or(line, |(_, text)| text);
            words(spoken)
        })
        .collect()
}
