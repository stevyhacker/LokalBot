pub const GENERATED_MARKER: &str = "<!-- Generated by LokalBot routine. -->";
const TIME_LIMIT: Duration = Duration::from_secs(30);
const TICK: Duration = Duration::from_secs(60);
/// Characters of a meeting's summary a follow-up quotes.
const SOURCE_SUMMARY_CHARACTERS: usize = 18_000;

#[derive(Debug, thiserror::Error)]
pub enum RoutineError {
    #[error(
        "Routine output stopped because {0} already exists with different content. The existing file was preserved."
    )]
    DestinationCollision(String),
    #[error(
        "Routine output stopped because {0} resolves outside the chosen folder or through a file symlink."
    )]
    UnsafeDestination(String),
    #[error("The meeting needed by this routine is no longer in the local library.")]
    MissingMeeting,
    #[error("The routine exceeded its 30-second safety limit.")]
    TimedOut,
}

/// A routine's output, ready to write.
#[derive(Clone, Debug, PartialEq)]
pub struct Prepared {
    pub folder: &'static str,
    pub file: String,
    pub body: String,
}

impl Prepared {
    pub fn fingerprint(&self) -> String {
        sha256_hex(self.body.as_bytes())
    }
}

fn clean(value: &str) -> String {
    value
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('`', "\\`")
}

fn display_date(at: DateTime<Utc>) -> String {
    at.with_timezone(&Local).format("%b %-d, %Y").to_string()
}

fn duration(seconds: f64) -> String {
    let minutes = (seconds.round() as i64 / 60).max(0);
    if minutes >= 60 {
        format!("{}h {}m", minutes / 60, minutes % 60)
    } else {
        format!("{minutes}m")
    }
}

fn day_key(at: DateTime<Utc>) -> String {
    at.with_timezone(&Local).format("%Y-%m-%d").to_string()
}

fn reference_action_line(reference: &ActionReference) -> String {
    let mut suffix: Vec<String> = Vec::new();
    if let Some(owner) = reference.owner.as_deref().filter(|o| !o.is_empty()) {
        suffix.push(format!("owner: {}", clean(owner)));
    }
    if let Some(due) = reference.due.as_deref().filter(|d| !d.is_empty()) {
        suffix.push(format!("due: {}", clean(due)));
    }
    if reference.status == ActionStatus::Deferred {
        suffix.push("status: deferred".into());
    }
    let marker = if reference.status == ActionStatus::Done {
        "x"
    } else {
        " "
    };
    let details = if suffix.is_empty() {
        String::new()
    } else {
        format!(" ({})", suffix.join(", "))
    };
    format!("- [{marker}] {}{details}", clean(&reference.text))
}

fn thread_action_line(thread: &lokalbot_core::ActionThread) -> String {
    let mut suffix: Vec<String> = Vec::new();
    if let Some(owner) = thread.owner.as_deref().filter(|o| !o.is_empty()) {
        suffix.push(format!("owner: {}", clean(owner)));
    }
    if let Some(due) = thread.due.as_deref().filter(|d| !d.is_empty()) {
        suffix.push(format!("due: {}", clean(due)));
    }
    let status = thread.status();
    if status == ActionStatus::Deferred {
        suffix.push("status: deferred".into());
    }
    let mut sources: Vec<String> = Vec::new();
    for reference in &thread.references {
        let id = lokalbot_core::ids::short_id(&reference.meeting_id);
        if !sources.contains(&id) {
            sources.push(id);
        }
    }
    let listed: Vec<String> = sources.iter().map(|id| format!("`{id}`")).collect();
    suffix.push(format!("sources: {}", listed.join(", ")));
    let marker = if status == ActionStatus::Done {
        "x"
    } else {
        " "
    };
    format!(
        "- [{marker}] {} ({})",
        clean(&thread.text),
        suffix.join(", ")
    )
}

/// Open and deferred actions from meetings since `cutoff`.
fn recent_actions(library: &Library, meetings: &[Meeting], cutoff: DateTime<Utc>) -> Vec<String> {
    let mut recent: Vec<&Meeting> = meetings.iter().filter(|m| m.started_at >= cutoff).collect();
    recent.sort_by_key(|meeting| std::cmp::Reverse(meeting.started_at));
    let references: Vec<ActionReference> = recent
        .iter()
        .filter_map(|meeting| library.outcome_projection(meeting).ok().flatten())
        .flat_map(|projection| projection.action_references())
        .collect();
    cluster_threads(references)
        .iter()
        .filter(|thread| thread.status() != ActionStatus::Done)
        .map(thread_action_line)
        .collect()
}

fn post_meeting(library: &Library, meeting: &Meeting) -> String {
    let summary = library
        .summary(meeting)
        .ok()
        .flatten()
        .map(|summary| summary.trim().to_string());
    let projection = library.outcome_projection(meeting).ok().flatten();
    let mut lines = vec![
        format!("# Follow-up draft — {}", clean(&meeting.title)),
        String::new(),
        format!(
            "Meeting: `{}` · {}",
            meeting.short_id(),
            display_date(meeting.started_at)
        ),
        String::new(),
        "## Draft".to_string(),
        String::new(),
        "Thanks for the conversation. Here is my understanding of the outcomes:".to_string(),
    ];
    if let Some(projection) = &projection {
        if !projection.outcomes.decision_records.is_empty() {
            lines.extend([String::new(), "### Decisions".to_string(), String::new()]);
            lines.extend(
                projection
                    .outcomes
                    .decision_records
                    .iter()
                    .map(|decision| format!("- {}", clean(&decision.text))),
            );
        }
        let actions = projection.action_references();
        if !actions.is_empty() {
            lines.extend([String::new(), "### Actions".to_string(), String::new()]);
            lines.extend(actions.iter().map(reference_action_line));
        }
        if !projection.outcomes.open_questions.is_empty() {
            lines.extend([
                String::new(),
                "### Open questions".to_string(),
                String::new(),
            ]);
            lines.extend(
                projection
                    .outcomes
                    .open_questions
                    .iter()
                    .map(|question| format!("- {}", clean(question))),
            );
        }
    }
    if let Some(summary) = summary.filter(|summary| !summary.is_empty()) {
        lines.extend([
            String::new(),
            "## Source summary".to_string(),
            String::new(),
        ]);
        lines.push(summary.chars().take(SOURCE_SUMMARY_CHARACTERS).collect());
    }
    lines.extend([
        String::new(),
        "_Draft only. Review recipients and wording before sending._".to_string(),
    ]);
    lines.join("\n")
}

fn daily_standup(library: &Library, day: NaiveDate, meetings: &[Meeting]) -> Result<String> {
    let (today, _) = local_day_bounds(day);
    let yesterday = day - chrono::Duration::days(1);
    let (yesterday_start, _) = local_day_bounds(yesterday);
    let mut prior: Vec<&Meeting> = meetings
        .iter()
        .filter(|m| m.started_at >= yesterday_start && m.started_at <= today)
        .collect();
    prior.sort_by_key(|meeting| meeting.started_at);
    let snapshot = daily::snapshot(library, yesterday)?;
    let actions = recent_actions(library, meetings, today - chrono::Duration::days(14));
    let mut lines = vec![
        format!("# Daily stand-up — {}", display_date(today)),
        String::new(),
        "## Yesterday".to_string(),
        String::new(),
    ];
    if prior.is_empty() {
        lines.push("- No recorded meetings.".into());
    } else {
        lines.extend(
            prior
                .iter()
                .map(|m| format!("- {} (`{}`)", clean(&m.title), m.short_id())),
        );
    }
    lines.extend([
        format!(
            "- Tracked time: {} across {} apps.",
            duration(snapshot.stats.tracked_seconds),
            snapshot.stats.app_count
        ),
        String::new(),
        "## Carry-forward actions".to_string(),
        String::new(),
    ]);
    if actions.is_empty() {
        lines.push("- No extracted action candidates.".into());
    } else {
        lines.extend(actions.into_iter().take(20));
    }
    lines.extend([
        String::new(),
        "## Today".to_string(),
        String::new(),
        "- [ ] Choose the priorities to carry forward from the list above.".to_string(),
        String::new(),
        "_This is a local draft. Nothing was assigned, sent, or marked complete._".to_string(),
    ]);
    Ok(lines.join("\n"))
}

fn weekly_work_log(library: &Library, end: DateTime<Utc>, meetings: &[Meeting]) -> Result<String> {
    let start = end - chrono::Duration::days(7);
    let mut scoped: Vec<&Meeting> = meetings
        .iter()
        .filter(|m| m.started_at >= start && m.started_at <= end)
        .collect();
    scoped.sort_by_key(|meeting| meeting.started_at);
    let usage = library.app_time(start, end, 20)?;
    let mut decisions: Vec<String> = Vec::new();
    let mut references: Vec<ActionReference> = Vec::new();
    for meeting in &scoped {
        let Some(projection) = library.outcome_projection(meeting).ok().flatten() else {
            continue;
        };
        decisions.extend(
            projection
                .outcomes
                .decision_records
                .iter()
                .map(|decision| format!("- {} — `{}`", clean(&decision.text), meeting.short_id())),
        );
        references.extend(projection.action_references());
    }
    let actions: Vec<String> = cluster_threads(references)
        .iter()
        .map(thread_action_line)
        .collect();
    let mut lines = vec![
        format!("# Weekly work log — ending {}", display_date(end)),
        String::new(),
        format!("## Meetings ({})", scoped.len()),
        String::new(),
    ];
    if scoped.is_empty() {
        lines.push("_No recorded meetings._".into());
    } else {
        lines.extend(scoped.iter().map(|m| {
            format!(
                "- {}: {} (`{}`)",
                display_date(m.started_at),
                clean(&m.title),
                m.short_id()
            )
        }));
    }
    lines.extend([String::new(), "## Decisions".to_string(), String::new()]);
    if decisions.is_empty() {
        lines.push("_No extracted decisions._".into());
    } else {
        lines.extend(decisions);
    }
    lines.extend([
        String::new(),
        "## Action candidates".to_string(),
        String::new(),
    ]);
    if actions.is_empty() {
        lines.push("_No extracted actions._".into());
    } else {
        lines.extend(actions);
    }
    lines.extend([
        String::new(),
        "## App-time totals".to_string(),
        String::new(),
    ]);
    if usage.is_empty() {
        lines.push("_No tracked app activity._".into());
    } else {
        lines.extend(
            usage
                .iter()
                .map(|app| format!("- {}: {}", clean(&app.app), duration(app.duration_seconds))),
        );
    }
    Ok(lines.join("\n"))
}

fn unfinished_actions(library: &Library, at: DateTime<Utc>, meetings: &[Meeting]) -> String {
    let actions = recent_actions(library, meetings, at - chrono::Duration::days(14));
    let mut lines = vec![
        format!("# Unfinished action candidates — {}", display_date(at)),
        String::new(),
        "Open and deferred actions from the last fourteen days, using your saved corrections and completion state.".to_string(),
        String::new(),
    ];
    if actions.is_empty() {
        lines.push("_No extracted action candidates._".into());
    } else {
        lines.extend(actions);
    }
    lines.extend([
        String::new(),
        "_No source meeting or task system was modified._".to_string(),
    ]);
    lines.join("\n")
}

fn local_journal(library: &Library, day: NaiveDate) -> Result<String> {
    let snapshot = daily::snapshot(library, day)?;
    let mut lines = vec![
        format!("# Journal — {}", display_date(local_day_bounds(day).0)),
        String::new(),
        "## Digest".to_string(),
        String::new(),
    ];
    let digest = snapshot
        .digest
        .as_deref()
        .map(str::trim)
        .filter(|digest| !digest.is_empty());
    lines.push(
        digest
            .unwrap_or("_No day digest was generated._")
            .to_string(),
    );
    lines.extend([String::new(), "## Meetings".to_string(), String::new()]);
    if snapshot.meetings.is_empty() {
        lines.push("_No meetings._".into());
    } else {
        lines.extend(
            snapshot
                .meetings
                .iter()
                .map(|m| format!("- {} (`{}`)", clean(&m.title), m.id)),
        );
    }
    lines.extend([String::new(), "## Saved moments".to_string(), String::new()]);
    if snapshot.saved_moments.is_empty() {
        lines.push("_No saved moments._".into());
    } else {
        lines.extend(snapshot.saved_moments.iter().map(|moment| {
            let label = if moment.window_title.is_empty() {
                moment.app.clone()
            } else {
                format!("{} — {}", moment.app, moment.window_title)
            };
            format!("- {} (`screen:{}`)", clean(&label), moment.snapshot_id)
        }));
    }
    lines.extend([
        String::new(),
        "## Day stats".to_string(),
        String::new(),
        format!(
            "- Tracked time: {}",
            duration(snapshot.stats.tracked_seconds)
        ),
        format!("- Apps: {}", snapshot.stats.app_count),
        format!("- Context captures: {}", snapshot.stats.screenshot_count),
    ]);
    Ok(lines.join("\n"))
}

/// Builds a routine's output without writing anything.
pub fn prepare(
    library: &Library,
    kind: MemoryRoutineKind,
    reference: DateTime<Utc>,
    meeting_id: Option<Uuid>,
) -> Result<Prepared> {
    let meetings = library.list_meetings()?;
    let day = reference.with_timezone(&Local).date_naive();
    let (folder, file, text) = match kind {
        MemoryRoutineKind::PostMeetingFollowUp => {
            let meeting = meeting_id
                .and_then(|id| meetings.iter().find(|meeting| meeting.id == id))
                .ok_or(RoutineError::MissingMeeting)?;
            (
                "Post-meeting follow-ups",
                format!(
                    "{}-{}-follow-up.md",
                    meeting
                        .started_at
                        .with_timezone(&Local)
                        .format("%Y-%m-%d-%H%M"),
                    meeting.short_id()
                ),
                post_meeting(library, meeting),
            )
        }
        MemoryRoutineKind::DailyStandup => (
            "Daily stand-ups",
            format!("{}-stand-up.md", day_key(reference)),
            daily_standup(library, day, &meetings)?,
        ),
        MemoryRoutineKind::WeeklyWorkLog => (
            "Weekly work logs",
            format!("{}-work-log.md", day_key(reference)),
            weekly_work_log(library, reference, &meetings)?,
        ),
        MemoryRoutineKind::UnfinishedActions => (
            "Unfinished actions",
            format!("{}-actions.md", day_key(reference)),
            unfinished_actions(library, reference, &meetings),
        ),
        MemoryRoutineKind::LocalJournal => (
            "Journal",
            format!("{}.md", day_key(reference)),
            local_journal(library, day)?,
        ),
    };
    let redacted = lokalbot_ai::sanitize::redact(&text);
    Ok(Prepared {
        folder,
        file,
        body: format!("{GENERATED_MARKER}\n\n{}\n", redacted.trim()),
    })
}

#[cfg(unix)]
fn create_private_directory(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::DirBuilderExt as _;
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(path)
}

#[cfg(not(unix))]
fn create_private_directory(path: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(path)
}

/// Writes a prepared routine under `destination`. The folder it lands in must
/// resolve inside the chosen one, so a link can't carry the file elsewhere.
pub fn write(output: &Prepared, destination: &Path) -> Result<PathBuf> {
    if !destination.exists() {
        create_private_directory(destination)?;
    }
    let root = std::fs::canonicalize(destination)?;
    let requested = destination.join(output.folder);
    create_private_directory(&requested)?;
    let directory = std::fs::canonicalize(&requested)?;
    if directory == root || !directory.starts_with(&root) {
        return Err(RoutineError::UnsafeDestination(requested.display().to_string()).into());
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::set_permissions(&directory, std::fs::Permissions::from_mode(0o700))?;
    }
    let path = directory.join(&output.file);
    match generated_file::write(output.body.as_bytes(), &path, GENERATED_MARKER) {
        Ok(_) => Ok(path),
        Err(WriteError::UnsafeDestination) => {
            Err(RoutineError::UnsafeDestination(path.display().to_string()).into())
        }
        Err(WriteError::Io(err)) => Err(err.into()),
        Err(_) => Err(RoutineError::DestinationCollision(
            path.file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default(),
        )
        .into()),
    }
}

/// One due routine.
#[derive(Clone, Debug, PartialEq)]
pub struct Job {
    pub kind: MemoryRoutineKind,
    pub reference: DateTime<Utc>,
    pub meeting_id: Option<Uuid>,
    pub run_token: String,
}

/// The newest instant at or before `now` on `weekday` (1 is Sunday, 7 Saturday,
/// as on the Mac) at `hour`.
pub fn most_recent_weekly_target(
    now: DateTime<Local>,
    weekday: u32,
    hour: u32,
) -> Option<DateTime<Utc>> {
    let weekday = weekday.clamp(1, 7);
    let hour = hour.min(23);
    let today = now.date_naive();
    let current = today.weekday().num_days_from_sunday() + 1;
    let back = (current + 7 - weekday) % 7;
    let mut day = today - chrono::Duration::days(i64::from(back));
    if back == 0 && now.hour() < hour {
        day -= chrono::Duration::days(7);
    }
    Local
        .from_local_datetime(&day.and_hms_opt(hour, 0, 0)?)
        .earliest()
        .map(|at| at.with_timezone(&Utc))
}

fn is_daily(kind: MemoryRoutineKind) -> bool {
    !kind.is_event_driven() && !kind.is_weekly()
}

/// What's due at `now`, whether or not it has run; finished tokens are skipped
/// when a job's output is known.
pub fn candidate_jobs(library: &Library, settings: &Settings, now: DateTime<Local>) -> Vec<Job> {
    let enabled = &settings.enabled_memory_routines;
    let current = now.with_timezone(&Utc);
    let mut jobs = Vec::new();
    if enabled.contains(&MemoryRoutineKind::PostMeetingFollowUp) {
        let cutoff = current - chrono::Duration::days(14);
        for meeting in library.list_meetings().unwrap_or_default() {
            if meeting.is_sample() || meeting.started_at < cutoff || meeting.started_at > current {
                continue;
            }
            if !library.meeting_dir(&meeting).join("summary.md").exists() {
                continue;
            }
            jobs.push(Job {
                kind: MemoryRoutineKind::PostMeetingFollowUp,
                reference: meeting.started_at,
                meeting_id: Some(meeting.id),
                run_token: format!(
                    "scheduled:postMeetingFollowUp:{}",
                    meeting.id.hyphenated().to_string().to_uppercase()
                ),
            });
        }
    }
    if now.hour() >= settings.memory_routine_hour.min(23) {
        let today = now.date_naive();
        let (start_of_today, _) = local_day_bounds(today);
        for kind in MemoryRoutineKind::ALL {
            if enabled.contains(&kind) && is_daily(kind) {
                jobs.push(Job {
                    kind,
                    reference: start_of_today,
                    meeting_id: None,
                    run_token: format!(
                        "scheduled:{}:{}",
                        kind.raw_value(),
                        today.format("%Y-%m-%d")
                    ),
                });
            }
        }
    }
    if enabled.contains(&MemoryRoutineKind::WeeklyWorkLog)
        && let Some(target) = most_recent_weekly_target(
            now,
            settings.memory_routine_weekday,
            settings.memory_routine_hour,
        )
    {
        jobs.push(Job {
            kind: MemoryRoutineKind::WeeklyWorkLog,
            reference: target,
            meeting_id: None,
            run_token: format!("scheduled:weeklyWorkLog:{}", day_key(target)),
        });
    }
    jobs
}

/// Runs `work` on its own thread and gives up after the safety limit. A stuck
/// read or write can't be interrupted, so it is left to finish on its own; its
/// run is already recorded as failed.
fn with_time_limit<T: Send + 'static>(
    work: impl FnOnce() -> Result<T> + Send + 'static,
) -> Result<T> {
    let (sender, receiver) = crossbeam_channel::bounded(1);
    std::thread::Builder::new()
        .name("lokalbot-routine".into())
        .spawn(move || {
            let _ = sender.send(work());
        })?;
    match receiver.recv_timeout(TIME_LIMIT) {
        Ok(result) => result,
        Err(_) => Err(RoutineError::TimedOut.into()),
    }
}

fn destination_id(path: &str) -> String {
    let mut material = format!("{}:", path.len()).into_bytes();
    material.extend(path.as_bytes());
    sha256_hex(&material)
}

/// Prepares and writes one job, recording the attempt. Unchanged bytes for a
/// finished token do nothing.
pub fn run_job(library: &Library, job: &Job, destination: &str) -> Result<Option<PathBuf>> {
    let scope = format!("{}:{}", job.run_token, destination_id(destination));
    let prepared = {
        let (library, kind, reference, meeting) =
            (library.clone(), job.kind, job.reference, job.meeting_id);
        with_time_limit(move || prepare(&library, kind, reference, meeting))
    };
    let prepared = match prepared {
        Ok(prepared) => prepared,
        Err(err) => {
            // Preparation may fail before output has a fingerprint. Record the
            // failure once; read-only preparation can recover next tick.
            let message = format!("{err:#}");
            let token = library.routine_revision_token(
                &scope,
                &format!("prepare-error:{}", destination_id(&message)),
            )?;
            if !library.routine_has_finished(&token)? {
                let id = library.begin_routine_run(job.kind, &token, job.meeting_id, Utc::now())?;
                library.finish_routine_run(id, "failed", None, Some(&message), Utc::now())?;
                return Err(err);
            }
            return Ok(None);
        }
    };
    let token = library.routine_revision_token(&scope, &prepared.fingerprint())?;
    if library.routine_has_finished(&token)? {
        return Ok(None);
    }
    let id = library.begin_routine_run(job.kind, &token, job.meeting_id, Utc::now())?;
    let destination = PathBuf::from(destination);
    match with_time_limit(move || write(&prepared, &destination)) {
        Ok(path) => {
            library.finish_routine_run(
                id,
                "succeeded",
                Some(&path.display().to_string()),
                None,
                Utc::now(),
            )?;
            Ok(Some(path))
        }
        Err(err) => {
            library.finish_routine_run(
                id,
                "failed",
                None,
                Some(&format!("{err:#}")),
                Utc::now(),
            )?;
            Err(err)
        }
    }
}

/// What Settings shows about routines.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct RoutineStatus {
    pub is_running: bool,
    pub current: Option<MemoryRoutineKind>,
    pub last_run_at: Option<DateTime<Utc>>,
    pub last_output: Option<PathBuf>,
    pub last_error: Option<String>,
    pub recent_runs: Vec<lokalbot_core::routines::RoutineRun>,
    pub due_count: usize,
    pub running_count: usize,
}

impl RoutineStatus {
    pub fn pending_count(&self) -> usize {
        self.due_count + self.running_count
    }
}

#[derive(Default)]
pub struct Routines {
    status: Mutex<RoutineStatus>,
    manual: Mutex<Vec<MemoryRoutineKind>>,
    wake: AtomicBool,
}

impl Routines {
    /// Rebuilds prepared output after a correction, completion or deletion.
    /// Finished revisions stay in the audit trail; changed bytes get a new token.
    pub fn reconsider_evidence(&self) {
        self.wake.store(true, Ordering::Relaxed);
    }

    pub fn run_now(&self, kind: MemoryRoutineKind) {
        if kind.is_event_driven() {
            return;
        }
        self.manual.lock().push(kind);
        self.wake.store(true, Ordering::Relaxed);
    }

    pub fn status(&self) -> RoutineStatus {
        self.status.lock().clone()
    }
}

fn manual_job(kind: MemoryRoutineKind) -> Job {
    let now = Utc::now();
    Job {
        kind,
        reference: now,
        meeting_id: None,
        run_token: format!(
            "manual:{}:{}:{}",
            kind.raw_value(),
            lokalbot_core::time::to_epoch(now),
            Uuid::new_v4().hyphenated().to_string().to_uppercase()
        ),
    }
}

/// Meeting recording and dictation take priority over routines.
fn can_run(shared: &Shared) -> bool {
    !shared.capture_active.load(Ordering::Relaxed)
        && !shared.recording_active.load(Ordering::Relaxed)
}

fn publish(shared: &Shared, change: impl FnOnce(&mut RoutineStatus)) {
    let status = {
        let mut status = shared.routines.status.lock();
        change(&mut status);
        status.running_count = shared.library.running_routine_count();
        status.recent_runs = shared.library.recent_routine_runs(12).unwrap_or_default();
        status.clone()
    };
    shared.emit(EngineEvent::Routines(Box::new(status)));
}

fn tick(shared: &Shared) {
    let library = &shared.library;
    let settings = shared.settings();
    let manual: Vec<MemoryRoutineKind> = std::mem::take(&mut *shared.routines.manual.lock());
    if !settings.memory_routines_enabled
        || settings.memory_routine_folder.is_empty()
        || !can_run(shared)
    {
        return;
    }
    let mut jobs: Vec<Job> = manual
        .into_iter()
        .filter(|kind| settings.enabled_memory_routines.contains(kind))
        .map(manual_job)
        .collect();
    jobs.extend(candidate_jobs(library, &settings, Local::now()));
    if jobs.is_empty() {
        return;
    }
    let folder = settings.memory_routine_folder.clone();
    publish(shared, |status| {
        status.is_running = true;
        status.due_count = jobs.len();
    });
    let mut remaining = jobs.len();
    for job in jobs {
        let current = shared.settings();
        if shared.is_shutting_down()
            || !current.memory_routines_enabled
            || current.memory_routine_folder != folder
        {
            break;
        }
        publish(shared, |status| status.current = Some(job.kind));
        let result = run_job(library, &job, &folder);
        remaining -= 1;
        match result {
            Ok(Some(path)) => publish(shared, |status| {
                status.last_run_at = Some(Utc::now());
                status.last_output = Some(path);
                status.last_error = None;
                status.due_count = remaining;
            }),
            Ok(None) => {
                shared.routines.status.lock().due_count = remaining;
            }
            Err(err) => {
                let message = format!("Memory routine failed: {err:#}");
                log::warn!("{message}");
                shared.error(message.clone());
                publish(shared, |status| {
                    status.last_error = Some(message);
                    status.due_count = remaining;
                });
            }
        }
    }
    publish(shared, |status| {
        status.is_running = false;
        status.current = None;
        status.due_count = 0;
    });
}

pub(crate) fn start(shared: Arc<Shared>) {
    let spawned = std::thread::Builder::new()
        .name("lokalbot-routines".into())
        .spawn(move || {
            publish(&shared, |_| {});
            while !shared.is_shutting_down() {
                tick(&shared);
                let until = Instant::now() + TICK;
                while Instant::now() < until && !shared.is_shutting_down() {
                    if shared.routines.wake.swap(false, Ordering::Relaxed) {
                        break;
                    }
                    std::thread::sleep(Duration::from_millis(500));
                }
            }
        });
    if let Err(err) = spawned {
        log::warn!("could not start routines: {err}");
    }
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use chrono::Duration as Span;
    use lokalbot_core::LibraryPaths;

    use super::*;

    fn library(dir: &Path) -> Library {
        Library::open(LibraryPaths::new(dir.join("library"))).unwrap()
    }

    fn outcomes_file(library: &Library, meeting: &Meeting) {
        std::fs::write(
            library.meeting_dir(meeting).join("outcomes.json"),
            serde_json::json!({
                "decisions": ["Ship on Friday"],
                "openQuestions": ["Who owns QA?"],
                "actionItems": [
                    {"id": "a1", "schemaVersion": 2, "text": "Send the notes", "owner": "Me",
                     "due": "Friday", "isForUser": true, "importance": 2, "citations": []},
                    {"id": "a2", "schemaVersion": 2, "text": "Review `the` doc", "owner": "Ana",
                     "isForUser": false, "importance": 1, "citations": []},
                ],
            })
            .to_string(),
        )
        .unwrap();
    }

    fn meeting(library: &Library, title: &str, started: DateTime<Utc>) -> Meeting {
        let mut meeting = library.create_meeting(title, "Zoom", started).unwrap();
        meeting.ended_at = Some(started + Span::minutes(30));
        library.save_meeting(&meeting).unwrap();
        std::fs::write(
            library.meeting_dir(&meeting).join("summary.md"),
            "password=hunter2secret\n\nThe summary.\n",
        )
        .unwrap();
        outcomes_file(library, &meeting);
        meeting
    }

    #[test]
    fn each_routine_renders_its_own_file_with_the_marker_and_no_secrets() {
        let dir = tempfile::tempdir().unwrap();
        let library = library(dir.path());
        let now = Utc::now();
        let source = meeting(&library, "Atlas sync", now - Span::hours(30));
        let follow_up = prepare(
            &library,
            MemoryRoutineKind::PostMeetingFollowUp,
            source.started_at,
            Some(source.id),
        )
        .unwrap();
        assert_eq!(follow_up.folder, "Post-meeting follow-ups");
        assert!(
            follow_up
                .file
                .ends_with(&format!("-{}-follow-up.md", source.short_id()))
        );
        assert!(follow_up.body.starts_with(GENERATED_MARKER));
        assert!(follow_up.body.contains("# Follow-up draft — Atlas sync"));
        assert!(follow_up.body.contains("### Decisions\n\n- Ship on Friday"));
        assert!(
            follow_up
                .body
                .contains("- [ ] Send the notes (owner: Me, due: Friday)")
        );
        assert!(
            follow_up
                .body
                .contains("- [ ] Review \\`the\\` doc (owner: Ana)")
        );
        assert!(
            follow_up
                .body
                .contains("### Open questions\n\n- Who owns QA?")
        );
        assert!(
            follow_up
                .body
                .contains("_Draft only. Review recipients and wording before sending._")
        );
        assert!(!follow_up.body.contains("hunter2secret"));
        assert!(follow_up.body.ends_with('\n'));

        let standup = prepare(&library, MemoryRoutineKind::DailyStandup, now, None).unwrap();
        assert_eq!(standup.folder, "Daily stand-ups");
        assert!(standup.file.ends_with("-stand-up.md"));
        assert!(standup.body.contains("## Yesterday"));
        assert!(standup.body.contains("## Carry-forward actions"));
        assert!(
            standup
                .body
                .contains(&format!("sources: `{}`", source.short_id()))
        );
        assert!(
            standup
                .body
                .contains("Nothing was assigned, sent, or marked complete.")
        );

        let weekly = prepare(&library, MemoryRoutineKind::WeeklyWorkLog, now, None).unwrap();
        assert_eq!(weekly.folder, "Weekly work logs");
        assert!(weekly.body.contains("## Meetings (1)"));
        assert!(
            weekly
                .body
                .contains(&format!("- Ship on Friday — `{}`", source.short_id()))
        );
        assert!(weekly.body.contains("_No tracked app activity._"));

        let actions = prepare(&library, MemoryRoutineKind::UnfinishedActions, now, None).unwrap();
        assert_eq!(actions.folder, "Unfinished actions");
        assert!(actions.file.ends_with("-actions.md"));
        assert!(actions.body.contains("- [ ] Send the notes"));

        let journal = prepare(&library, MemoryRoutineKind::LocalJournal, now, None).unwrap();
        assert_eq!(journal.folder, "Journal");
        assert!(
            journal
                .body
                .contains("## Digest\n\n_No day digest was generated._")
        );
        assert!(journal.body.contains("- Context captures: 0"));

        let missing = prepare(
            &library,
            MemoryRoutineKind::PostMeetingFollowUp,
            now,
            Some(Uuid::new_v4()),
        );
        assert!(
            missing
                .unwrap_err()
                .downcast_ref::<RoutineError>()
                .is_some()
        );
    }

    #[test]
    fn a_write_stays_inside_the_folder_and_keeps_existing_files() {
        let dir = tempfile::tempdir().unwrap();
        let destination = dir.path().join("routines");
        let output = Prepared {
            folder: "Journal",
            file: "2026-10-15.md".into(),
            body: format!("{GENERATED_MARKER}\n\none\n"),
        };
        let path = write(&output, &destination).unwrap();
        assert!(path.starts_with(std::fs::canonicalize(&destination).unwrap()));
        assert!(path.ends_with("Journal/2026-10-15.md"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt as _;
            let mode = std::fs::metadata(path.parent().unwrap())
                .unwrap()
                .permissions()
                .mode();
            assert_eq!(mode & 0o777, 0o700);
        }
        // Someone else's file under the name is preserved.
        std::fs::write(&path, "mine").unwrap();
        let err = write(&output, &destination).unwrap_err();
        assert!(matches!(
            err.downcast_ref::<RoutineError>(),
            Some(RoutineError::DestinationCollision(_))
        ));
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "mine");
        #[cfg(unix)]
        {
            // A folder that leads elsewhere is refused.
            let outside = dir.path().join("outside");
            std::fs::create_dir_all(&outside).unwrap();
            let linked = dir.path().join("linked");
            std::fs::create_dir_all(&linked).unwrap();
            std::os::unix::fs::symlink(&outside, linked.join("Journal")).unwrap();
            let err = write(&output, &linked).unwrap_err();
            assert!(matches!(
                err.downcast_ref::<RoutineError>(),
                Some(RoutineError::UnsafeDestination(_))
            ));
            assert_eq!(std::fs::read_dir(&outside).unwrap().count(), 0);
        }
    }

    #[test]
    fn a_job_runs_once_per_revision_and_failures_are_recorded_once() {
        let dir = tempfile::tempdir().unwrap();
        let library = library(dir.path());
        let destination = dir.path().join("routines").display().to_string();
        let source = meeting(&library, "Atlas sync", Utc::now() - Span::hours(2));
        let job = Job {
            kind: MemoryRoutineKind::PostMeetingFollowUp,
            reference: source.started_at,
            meeting_id: Some(source.id),
            run_token: "scheduled:postMeetingFollowUp:x".into(),
        };
        let path = run_job(&library, &job, &destination).unwrap().unwrap();
        assert!(path.is_file());
        let runs = library.recent_routine_runs(12).unwrap();
        assert_eq!(runs.len(), 1);
        assert_eq!(runs[0].status, "succeeded");
        assert_eq!(runs[0].output_path.as_deref(), Some(path.to_str().unwrap()));
        // Nothing changed: no second write and no second row.
        assert_eq!(run_job(&library, &job, &destination).unwrap(), None);
        assert_eq!(library.recent_routine_runs(12).unwrap().len(), 1);
        // A correction changes the bytes, so a new revision runs.
        std::fs::write(
            library.meeting_dir(&source).join("summary.md"),
            "Corrected.",
        )
        .unwrap();
        assert!(run_job(&library, &job, &destination).unwrap().is_some());
        assert_eq!(library.recent_routine_runs(12).unwrap().len(), 2);
        assert!(
            std::fs::read_to_string(&path)
                .unwrap()
                .contains("Corrected.")
        );

        // A person's edit stops further revisions, once, without a tight loop.
        std::fs::write(&path, format!("{GENERATED_MARKER}\nedited")).unwrap();
        std::fs::write(library.meeting_dir(&source).join("summary.md"), "Again.").unwrap();
        assert!(run_job(&library, &job, &destination).is_err());
        assert_eq!(run_job(&library, &job, &destination).unwrap(), None);
        let runs = library.recent_routine_runs(12).unwrap();
        assert_eq!(runs[0].status, "failed");
        assert!(runs[0].error.as_deref().unwrap().contains("already exists"));
        assert!(std::fs::read_to_string(&path).unwrap().contains("edited"));

        // A missing meeting fails in preparation, also once.
        let lost = Job {
            meeting_id: Some(Uuid::new_v4()),
            run_token: "scheduled:lost".into(),
            ..job
        };
        assert!(run_job(&library, &lost, &destination).is_err());
        assert_eq!(run_job(&library, &lost, &destination).unwrap(), None);
    }

    fn local(day: NaiveDate, hour: u32) -> DateTime<Local> {
        Local
            .from_local_datetime(&day.and_hms_opt(hour, 0, 0).unwrap())
            .earliest()
            .unwrap()
    }

    #[test]
    fn weekly_targets_look_back_to_the_chosen_weekday_sunday_first() {
        // 2026-10-15 is a Thursday, the Mac's weekday 5.
        let thursday = NaiveDate::from_ymd_opt(2026, 10, 15).unwrap();
        assert_eq!(thursday.weekday().num_days_from_sunday() + 1, 5);
        let at = |day, hour| local(day, hour).with_timezone(&Utc);
        assert_eq!(
            most_recent_weekly_target(local(thursday, 10), 5, 8),
            Some(at(thursday, 8))
        );
        // Before the hour on the day itself: last week's.
        assert_eq!(
            most_recent_weekly_target(local(thursday, 7), 5, 8),
            Some(at(thursday - Span::days(7), 8))
        );
        // Friday (6) was six days ago, Sunday (1) four.
        assert_eq!(
            most_recent_weekly_target(local(thursday, 10), 6, 8),
            Some(at(thursday - Span::days(6), 8))
        );
        assert_eq!(
            most_recent_weekly_target(local(thursday, 10), 1, 8),
            Some(at(thursday - Span::days(4), 8))
        );
    }

    #[test]
    fn due_jobs_follow_the_enabled_routines_and_the_hour() {
        let dir = tempfile::tempdir().unwrap();
        let library = library(dir.path());
        let now = Local::now();
        let day = now.date_naive();
        let yesterday = local(day - Span::days(1), 12).with_timezone(&Utc);
        let sample_free = meeting(&library, "Real", yesterday);
        let mut sample = meeting(&library, "Sample", yesterday - Span::hours(1));
        sample.sample_id = Some("sample".into());
        library.save_meeting(&sample).unwrap();
        let old = meeting(&library, "Old", now.with_timezone(&Utc) - Span::days(20));
        let settings = Settings {
            memory_routine_hour: 8,
            ..Settings::default()
        };
        let morning = local(day, 7);
        let jobs = candidate_jobs(&library, &settings, morning);
        let follow_ups: Vec<&Job> = jobs
            .iter()
            .filter(|job| job.kind == MemoryRoutineKind::PostMeetingFollowUp)
            .collect();
        // Fourteen days back, never the made-up sample.
        assert!(
            follow_ups
                .iter()
                .all(|job| job.meeting_id != Some(sample.id))
        );
        assert!(follow_ups.iter().all(|job| job.meeting_id != Some(old.id)));
        assert!(
            !jobs
                .iter()
                .any(|job| job.kind == MemoryRoutineKind::DailyStandup)
        );
        let later = local(day, 9);
        let jobs = candidate_jobs(&library, &settings, later);
        let expected = format!("scheduled:dailyStandup:{}", day.format("%Y-%m-%d"));
        assert!(jobs.iter().any(|job| job.run_token == expected));
        assert!(
            jobs.iter()
                .any(|job| job.meeting_id == Some(sample_free.id))
        );
        assert!(
            jobs.iter()
                .any(|job| job.kind == MemoryRoutineKind::WeeklyWorkLog)
        );
        let only_journal = Settings {
            enabled_memory_routines: vec![MemoryRoutineKind::LocalJournal],
            memory_routine_hour: 8,
            ..Settings::default()
        };
        let jobs = candidate_jobs(&library, &only_journal, later);
        assert_eq!(jobs.len(), 1);
        assert_eq!(jobs[0].kind, MemoryRoutineKind::LocalJournal);
    }
}
