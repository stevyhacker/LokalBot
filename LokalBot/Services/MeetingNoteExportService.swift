import Foundation

struct MeetingNoteExportConfiguration: Equatable, Sendable {
    var destinationDirectory: URL
    var format: DailyMemoryExportKind
    var includesTranscript: Bool
}

/// What one pass did. Fingerprints are of each meeting's sources, so the next
/// pass renders only the meetings whose notes could have changed.
struct MeetingNoteExportReport: Equatable, Sendable {
    var fingerprints: [UUID: String] = [:]
    var written: [URL] = []
    /// Meetings whose note could not be written, tried again on a later pass.
    var failures: [String] = []
}

/// Optional one-note-per-meeting export to a folder the person picks, such as
/// an Obsidian vault or a Logseq OG graph's `pages` folder: the summary with
/// the action list as LokalBot shows it, people and tracked projects as links,
/// and optionally the transcript.
///
/// A note is named when it is first written and keeps that name, so links to
/// it from other notes survive a renamed meeting. It is refreshed only while
/// it still holds the bytes LokalBot wrote (the same hash sidecar as the daily
/// export). A note the person edited, deleted, or moved is theirs: LokalBot
/// leaves it alone and does not write that meeting again. Deleting a meeting
/// in LokalBot leaves its note in place, like every other export.
struct MeetingNoteExportService {
    static let generatedFileMarker = "<!-- Generated by LokalBot meeting note export. -->"
    /// Part of every fingerprint: changing how notes look refreshes them all.
    static let renderVersion = "1"

    enum Outcome: Equatable {
        case written(URL)
        case unchanged(URL)
        /// Edited, deleted, or moved by the person, or a file LokalBot did
        /// not write holds the name.
        case left
    }

    /// Everything one note shows, read from the library.
    struct Note: Equatable {
        var meeting: Meeting
        var people: [String] = []
        var projects: [String] = []
        var summary: String?
        var actions: [OutcomeActionReference] = []
        var transcript: String?
    }

    var root: URL
    var calendar: Calendar

    init(root: URL = SessionLookup.storageRootURL, calendar: Calendar = .current) {
        self.root = root
        self.calendar = calendar
    }

    /// Writes or refreshes the note of every finished meeting with a summary,
    /// or a transcript when transcripts are included. A meeting whose
    /// fingerprint matches `previous` is skipped without being read.
    func export(_ configuration: MeetingNoteExportConfiguration,
                previous: [UUID: String] = [:]) throws -> MeetingNoteExportReport {
        let fileManager = FileManager.default
        // The sample meeting is made up, so it never lands in the user's notes.
        let meetings = try SessionLookup.loadAllMeetings(root: root).filter { !$0.isSample }
        try Task.checkCancellation()
        try fileManager.createDirectory(
            at: configuration.destinationDirectory, withIntermediateDirectories: true)
        let existing = try ExistingNotes(directory: configuration.destinationDirectory)

        // Sources are stamped before anything is read from them: a file that
        // changes after its stamp is taken changes the next pass's stamp too.
        var stamps: [UUID: String] = [:]
        for meeting in meetings where meeting.endedAt != nil {
            let folder = folderURL(for: meeting)
            let hasSummary = fileManager.fileExists(atPath: folder.appendingPathComponent("summary.md").path)
            let hasTranscript = fileManager.fileExists(atPath: folder.appendingPathComponent("transcript.md").path)
            guard hasSummary || (hasTranscript && configuration.includesTranscript) else { continue }
            stamps[meeting.id] = Self.sourceStamp(folder)
        }
        try Task.checkCancellation()
        let connections = Connections(meetings: meetings, root: root)
        let configurationKey = "\(configuration.format.rawValue)|\(configuration.includesTranscript)"

        var report = MeetingNoteExportReport()
        for meeting in meetings {
            guard let stamp = stamps[meeting.id] else { continue }
            try Task.checkCancellation()
            let people = connections.people[meeting.id] ?? []
            let fingerprint = ContentFingerprint.fields([
                Self.renderVersion, configurationKey, stamp,
                people.joined(separator: "\n"), connections.projectsKey,
            ])
            if previous[meeting.id] == fingerprint {
                report.fingerprints[meeting.id] = fingerprint
                continue
            }
            do {
                let note = loadNote(meeting, people: people, connections: connections,
                                    includesTranscript: configuration.includesTranscript)
                let outcome = try write(note, configuration: configuration, existing: existing)
                report.fingerprints[meeting.id] = fingerprint
                if case .written(let url) = outcome { report.written.append(url) }
            } catch is CancellationError {
                throw CancellationError()
            } catch {
                lokalbotLog("meeting note export failed for \(SessionLookup.shortID(meeting.id)): "
                    + error.localizedDescription)
                report.failures.append("\(meeting.displayTitle): \(error.localizedDescription)")
            }
        }
        return report
    }

    func write(_ note: Note, configuration: MeetingNoteExportConfiguration,
               existing: ExistingNotes) throws -> Outcome {
        let shortID = SessionLookup.shortID(note.meeting.id)
        let name: String
        if let current = existing.names[shortID] {
            name = current
        } else if existing.removed.contains(shortID) {
            return .left
        } else {
            name = fileName(for: note.meeting)
        }
        let url = configuration.destinationDirectory.appendingPathComponent(name, isDirectory: false)
        let data = Data(render(note, format: configuration.format).utf8)
        try Task.checkCancellation()
        do {
            let changed = try GeneratedFileWriter.write(data, to: url, marker: Self.generatedFileMarker)
            return changed ? .written(url) : .unchanged(url)
        } catch is GeneratedFileWriter.WriteError {
            return .left
        }
    }

    private func loadNote(_ meeting: Meeting, people: [String], connections: Connections,
                          includesTranscript: Bool) -> Note {
        let folder = folderURL(for: meeting)
        let summary = Self.contents(folder.appendingPathComponent("summary.md"))
        let transcript = Self.contents(folder.appendingPathComponent("transcript.md"))
        let projection = connections.projections[meeting.id]
        var outcomeTexts = projection?.actionReferences.map(\.text) ?? []
        outcomeTexts += projection?.outcomes.decisionRecords.map(\.text) ?? []
        return Note(
            meeting: meeting,
            people: people,
            projects: connections.projects(
                for: meeting, texts: [summary ?? ""] + outcomeTexts, transcript: transcript),
            summary: summary,
            actions: projection?.actionReferences ?? [],
            transcript: includesTranscript ? transcript : nil)
    }

    private func folderURL(for meeting: Meeting) -> URL {
        root.appendingPathComponent(meeting.relativePath, isDirectory: true)
    }

    // MARK: - Rendering

    func render(_ note: Note, format: DailyMemoryExportKind) -> String {
        let meeting = note.meeting
        let title = singleLine(meeting.displayTitle)
        let shortID = SessionLookup.shortID(meeting.id)
        let start = time(meeting.startedAt)
        var sections: [String] = []
        switch format {
        case .markdown:
            var facts = [
                "- **When:** \(displayDate(meeting.startedAt)), \(start) · \(meeting.durationLabel)",
                "- **App:** \(inline(meeting.appName))",
            ]
            if !note.people.isEmpty {
                facts.append("- **People:** " + note.people.map(inline).joined(separator: ", "))
            }
            if !note.projects.isEmpty {
                facts.append("- **Projects:** " + note.projects.map(inline).joined(separator: ", "))
            }
            facts.append("- **Meeting:** `\(shortID)`")
            sections.append("\(Self.generatedFileMarker)\n\n# \(inline(title))")
            sections.append(facts.joined(separator: "\n"))
        case .obsidian:
            var lines = [
                "---",
                "aliases:",
                "  - \(yamlString(title))",
                "date: \(dayKey(meeting.startedAt))",
                "time: \(yamlString(start))",
                "duration: \(yamlString(meeting.durationLabel))",
                "app: \(yamlString(meeting.appName))",
            ]
            let people = note.people.compactMap(link)
            if !people.isEmpty { lines += ["people:"] + people.map { "  - \(yamlString($0))" } }
            let projects = note.projects.compactMap(link)
            if !projects.isEmpty { lines += ["projects:"] + projects.map { "  - \(yamlString($0))" } }
            lines += [
                "tags:",
                "  - lokalbot/meeting",
                "lokalbot-id: \(yamlString(shortID))",
                "source: LokalBot",
                "---",
            ]
            sections.append(lines.joined(separator: "\n"))
            sections.append("\(Self.generatedFileMarker)\n\n# \(inline(title))")
        case .logseq:
            var lines = ["date:: \(dayKey(meeting.startedAt))"]
            let people = note.people.compactMap(link)
            if !people.isEmpty { lines.append("people:: " + people.joined(separator: ", ")) }
            let projects = note.projects.compactMap(link)
            if !projects.isEmpty { lines.append("projects:: " + projects.joined(separator: ", ")) }
            lines += ["tags:: lokalbot, meeting", "lokalbot-id:: \(shortID)", "source:: LokalBot"]
            sections.append(lines.joined(separator: "\n"))
            sections.append("\(Self.generatedFileMarker)\n\n# \(inline(title))")
            sections.append("\(start) · \(meeting.durationLabel) · \(inline(meeting.appName))")
        }

        let actions = note.actions.isEmpty ? nil : actionLines(note.actions, format: format)
        if let summary = note.summary {
            let body = actions.map {
                MeetingSummaryOutcomeSynchronizer.replacingActionItems(in: summary, with: $0)
            } ?? summary
            sections.append(redacted(body.trimmingCharacters(in: .whitespacesAndNewlines)))
        } else if let actions {
            sections.append(redacted((["## Action items", ""] + actions).joined(separator: "\n")))
        }
        if let transcript = note.transcript {
            sections.append("## Transcript\n\n" + redacted(transcript))
        }
        return sections.joined(separator: "\n\n") + "\n"
    }

    /// The action list as LokalBot shows it, grouped like `summary.md`, with
    /// the person's corrections applied and completed actions checked off.
    func actionLines(_ actions: [OutcomeActionReference], format: DailyMemoryExportKind) -> [String] {
        typealias Item = (action: MeetingOutcomes.ActionItem, status: OutcomeStatus)
        let items: [Item] = actions.map { (action: $0.effectiveAction, status: $0.status) }
        func list(_ group: [Item], includeOwner: Bool) -> [String] {
            guard !group.isEmpty else { return ["None"] }
            return group.map { item in
                let marker = switch (format, item.status) {
                case (.logseq, .done): "- DONE"
                case (.logseq, _): "- TODO"
                case (_, .done): "- [x]"
                default: "- [ ]"
                }
                let owner = includeOwner ? singleLine(item.action.owner ?? "Owner not stated") + ": " : ""
                let due = item.action.due.map { " — due \(singleLine($0))" } ?? ""
                let deferred = item.status == .deferred ? " — deferred" : ""
                let citation = item.action.citations.min { $0.start < $1.start }
                    .map { " — [\(Transcript.stamp($0.start))]" } ?? ""
                return "\(marker) \(owner)\(singleLine(item.action.displayText))\(due)\(deferred)\(citation)"
            }
        }
        var lines = ["### Me"] + list(items.filter { $0.action.isForUser }, includeOwner: false)
        lines += ["", "### Others"]
            + list(items.filter { !$0.action.isForUser && !$0.action.ownershipIsUnclear }, includeOwner: true)
        let unclear = items.filter { $0.action.ownershipIsUnclear }
        if !unclear.isEmpty { lines += ["", "### Owner unclear"] + list(unclear, includeOwner: false) }
        return lines
    }

    /// "2026-09-29 Atlas release sync (4f7c2a91).md": the date sorts notes,
    /// the title reads well in a vault, and the meeting's short id finds the
    /// note again after the meeting is renamed.
    func fileName(for meeting: Meeting) -> String {
        let forbidden = Set(#"\/:*?"<>|#^[]"#)
        let cleaned = String(meeting.displayTitle.map { character in
            forbidden.contains(character) || character.unicodeScalars.contains {
                CharacterSet.controlCharacters.contains($0)
            } ? " " : character
        })
        var title = singleLine(cleaned).drop { $0 == "." }.prefix(80)
        while title.last?.isWhitespace == true { title = title.dropLast() }
        let shown = title.isEmpty ? "Meeting" : String(title)
        return "\(dayKey(meeting.startedAt)) \(shown) (\(SessionLookup.shortID(meeting.id))).md"
    }

    /// The meeting short id in a note name from `fileName(for:)`.
    static func meetingID(inFileName name: String) -> String? {
        guard name.hasSuffix(").md"), let open = name.range(of: " (", options: .backwards) else { return nil }
        let id = name[open.upperBound..<name.index(name.endIndex, offsetBy: -4)]
        guard id.count == 8, id.allSatisfy({ "0123456789abcdef".contains($0) }) else { return nil }
        return String(id)
    }

    // MARK: - Sources

    /// Names, sizes, and modification dates of the files in a meeting folder.
    /// Processing, a correction, a completed action, and a renamed speaker or
    /// meeting each rewrite one of them.
    static func sourceStamp(_ folder: URL) -> String {
        let keys: Set<URLResourceKey> = [.contentModificationDateKey, .fileSizeKey, .isRegularFileKey]
        let files = (try? FileManager.default.contentsOfDirectory(
            at: folder, includingPropertiesForKeys: Array(keys))) ?? []
        return files.compactMap { url -> String? in
            guard let values = try? url.resourceValues(forKeys: keys), values.isRegularFile == true else { return nil }
            let modified = values.contentModificationDate?.timeIntervalSince1970 ?? 0
            return "\(url.lastPathComponent):\(values.fileSize ?? 0):\(modified)"
        }
        .sorted()
        .joined(separator: "\n")
    }

    private static func contents(_ url: URL) -> String? {
        let text = (try? String(contentsOf: url, encoding: .utf8))?
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return text?.isEmpty == false ? text : nil
    }

    // MARK: - Formatting

    private func redacted(_ text: String) -> String {
        ScreenContextPrivacy.redact(text).text
    }

    /// An Obsidian or Logseq link, without the characters that end one.
    private func link(_ name: String) -> String? {
        let target = singleLine(String(name.filter { !"[]|#^".contains($0) }))
        return target.isEmpty ? nil : "[[\(target)]]"
    }

    /// A double-quoted YAML scalar, so titles with colons or quotes stay text.
    private func yamlString(_ value: String) -> String {
        var escaped = ""
        for scalar in singleLine(value).unicodeScalars {
            switch scalar {
            case "\\": escaped += "\\\\"
            case "\"": escaped += "\\\""
            default:
                if CharacterSet.controlCharacters.contains(scalar) {
                    escaped += " "
                } else {
                    escaped.unicodeScalars.append(scalar)
                }
            }
        }
        return "\"\(escaped)\""
    }

    private func dayKey(_ date: Date) -> String {
        let components = calendar.dateComponents([.year, .month, .day], from: date)
        return String(format: "%04d-%02d-%02d",
                      components.year ?? 0, components.month ?? 0, components.day ?? 0)
    }

    private func displayDate(_ date: Date) -> String {
        formatted(date, "MMMM d, yyyy")
    }

    private func time(_ date: Date) -> String {
        formatted(date, "HH:mm")
    }

    private func formatted(_ date: Date, _ format: String) -> String {
        let formatter = DateFormatter()
        formatter.calendar = calendar
        formatter.timeZone = calendar.timeZone
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = format
        return formatter.string(from: date)
    }

    private func singleLine(_ value: String) -> String {
        value.split(whereSeparator: \Character.isWhitespace).joined(separator: " ")
    }

    private func inline(_ value: String) -> String {
        singleLine(value)
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "`", with: "\\`")
            .replacingOccurrences(of: "*", with: "\\*")
            .replacingOccurrences(of: "_", with: "\\_")
            .replacingOccurrences(of: "[", with: "\\[")
            .replacingOccurrences(of: "]", with: "\\]")
            .replacingOccurrences(of: "|", with: "\\|")
    }
}

extension MeetingNoteExportService {
    /// The export folder's notes by meeting short id, and the meetings whose
    /// note is gone while its ownership sidecar remains: the person deleted
    /// the note or moved it elsewhere in the vault.
    struct ExistingNotes: Equatable {
        var names: [String: String] = [:]
        var removed: Set<String> = []

        init(directory: URL) throws {
            let entries = try FileManager.default.contentsOfDirectory(atPath: directory.path)
            let present = Set(entries)
            var owned: Set<String> = []
            for entry in entries where entry.hasPrefix(".") && entry.hasSuffix(GeneratedFileWriter.sidecarSuffix) {
                let note = String(entry.dropFirst().dropLast(GeneratedFileWriter.sidecarSuffix.count))
                guard let id = MeetingNoteExportService.meetingID(inFileName: note) else { continue }
                if present.contains(note) { owned.insert(note) } else { removed.insert(id) }
            }
            for entry in entries.sorted() where !entry.hasPrefix(".") {
                guard let id = MeetingNoteExportService.meetingID(inFileName: entry) else { continue }
                // Two notes for one meeting: keep to the one LokalBot wrote.
                if let current = names[id], owned.contains(current) || !owned.contains(entry) { continue }
                names[id] = entry
            }
            removed.subtract(names.keys)
        }
    }

    /// People and tracked projects per meeting, joined with the same rules as
    /// the People and Projects pages, once per pass.
    struct Connections {
        var projections: [UUID: MeetingOutcomeProjection]
        var people: [UUID: [String]]
        var trackedProjects: [(name: String, terms: [Set<String>])]
        /// Changes when a project is tracked, renamed, or dropped, so every
        /// note's project links are looked at again.
        var projectsKey: String

        init(meetings: [Meeting], root: URL) {
            let projections = meetings.compactMap { MeetingOutcomeProjection.load(for: $0, root: root) }
            self.projections = Dictionary(projections.map { ($0.meeting.id, $0) }, uniquingKeysWith: { first, _ in first })
            let profiles = PeopleDirectory.build(.init(
                meetings: meetings, projections: projections,
                appliedNames: PeopleDirectory.loadAppliedNames(for: meetings, root: root),
                curation: PeopleCuration.load(libraryRoot: root) ?? PeopleCuration()))
            var people: [UUID: [String]] = [:]
            for profile in profiles {
                for id in profile.meetingIDs { people[id, default: []].append(profile.name) }
            }
            self.people = people.mapValues { $0.sorted() }
            let tracked = (ProjectCuration.load(libraryRoot: root) ?? ProjectCuration()).tracked
            trackedProjects = tracked.map { (name: $0.name, terms: $0.allNames.map(ProjectLinks.significantTerms)) }
            projectsKey = tracked.map { $0.allNames.joined(separator: "\t") }.joined(separator: "\n")
        }

        /// Tracked projects named in the meeting's title, notes, outcomes, or
        /// transcript, as on the Projects page.
        func projects(for meeting: Meeting, texts: [String], transcript: String?) -> [String] {
            guard !trackedProjects.isEmpty else { return [] }
            var words = ProjectLinks.words(meeting.displayTitle)
            words.formUnion(ProjectLinks.words(meeting.calendarTitle ?? ""))
            for text in texts { words.formUnion(ProjectLinks.words(text)) }
            if let transcript { words.formUnion(ProjectLinks.TranscriptText(markdown: transcript).words) }
            return trackedProjects.filter { ProjectLinks.matches($0.terms, words: words) }.map(\.name)
        }
    }
}
